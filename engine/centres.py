INFINITE = float("inf")


class GiveUp(Exception):
    """The procedure cannot continue; nothing is claimed."""


class NoContact(GiveUp):
    """No hypersurface of maximal contact was found for a presentation."""


class Frame:
    """A submanifold N of affine space, on an open set, with coordinates and derivations.

    N is given by the equations `rows` in the `variables`, on the open set
    where the `units` do not vanish. Variables determined rationally by an
    equation have been eliminated: `solved` keeps those equations, for the way back.
    """

    def __init__(self, variables, coords, rows=(), units=(), solved=()):
        self.variables = tuple(variables)
        self.coords = tuple(coords)         # variables that are local coordinates on N
        self.rows = tuple(rows)             # equations with invertible Jacobian in the other variables
        self.units = tuple(u for u in units if not getattr(u, "is_number", True) or u == 0)
        self.solved = tuple(solved)
        self._fields = {}
        self._basis = None
        self._reducer = None
        self._jets = {}
        self._inverted = {}
        self._cuts = {}
        self._empty = {}
        self._vanishing = {}
        self._unit = None

    def field(self, k):
        """The vector field D_k as {variable: coefficient}."""
        if k not in self._fields:
            others = [v for v in self.variables if v not in self.coords]
            if not others:
                self._fields[k] = {k: chart_expressions(self.variables).sympify(1)}
            else:
                self._fields[k] = frame_field(self.variables, self.rows, (*others, k))
        return self._fields[k]

    def basis(self):
        if self._basis is None:
            contracted = frame_locus(self.variables, self.rows, self.units, closure=True)
            self._basis = groebner(contracted, self.variables, known=len(contracted))
        return self._basis

    def over(self, x):
        """A variable t and a basis of (rows) + (t*x - 1) for an order that
        compares t first. The units are left out of it on purpose."""
        if x not in self._inverted:
            t = chart_expressions(self.variables).Dummy("over")
            self._inverted[x] = t, groebner((*self.rows, t*x - 1), (t, *self.variables), order="first")
        return self._inverted[x]

    def unit(self):
        """The product of the units, as a function on V(rows)."""
        if self._unit is None:
            value = chart_expressions(self.variables).sympify(1)
            for u in self.units:
                value = self.reduced(value*self.reduced(u))
            self._unit = value
        return self._unit

    def cut(self, x):
        """Bases that decide whether x divides a function on N: one of the
        ideal I0 = (rows) + (x), and one of I0 + (s*u - 1) for the product u
        of the units taken modulo I0 (None when u is constant there, False
        when u vanishes there: N does not meet x = 0)."""
        if x not in self._cuts:
            first = groebner((*self.rows, x), self.variables)
            u = chart_expressions(self.variables).sympify(1)
            for factor in self.units:
                factor = first.reduce(frame_function(self.variables, factor))[1]
                u = first.reduce(frame_function(self.variables, u*factor))[1]
            if u == 0:
                second = False
            elif u.is_number:
                second = None
            else:
                s = chart_expressions(self.variables).Dummy("unit")
                second = groebner((*first.exprs, s*u - 1), (s, *self.variables))
            self._cuts[x] = first, second
        return self._cuts[x]

    def reduced(self, f):
        """A smaller representative of the function f on N."""
        if not self.rows:
            return f
        return self._reduced_terms(frame_function(self.variables, f))

    def _reduced_terms(self, value):
        if self._reducer is None:
            self._reducer = groebner(self.rows, self.variables)
        return self._reducer.reduce(value)[1]

    def derivative(self, f, k):
        field = self.field(k)
        value = frame_derivative(self.variables, f, field)
        if len(field) == 1 and field.get(k) == 1:
            return value
        return self._reduced_terms(value)

    def vanishes(self, f):
        """Whether f is zero on N."""
        if f == 0:
            return True
        if not self.variables:
            return self.empty()
        if not self.rows and 0 not in self.units:
            return False
        if f in self._vanishing:
            return self._vanishing[f]
        residue = self.reduced(f)
        if not residue:
            answer = True
        elif self._basis is None and self.coords and self.units and self._witness(residue):
            answer = False
        else:
            answer = self.basis().contains(residue)
        self._vanishing[f] = answer
        return answer

    def _witness(self, f):
        """One point on the open frame with f nonzero disproves membership.
        Specialization only supplies witnesses. If these fibres miss the
        open set, use the exact saturated ideal of the whole chart."""
        for start in (2, -3, 5):
            fixed = tuple(v - (start+i) for i, v in enumerate(self.coords))
            if not self._empty_on(fixed, (*self.units, f)):
                return True
        return False

    def jet(self, f, order):
        """f and its derivatives of order < `order`: they vanish at the points where f has at least that order."""
        key = (f, order)
        if key not in self._jets:
            from . import native_library
            if (not self.rows and self.variables and order > 1 and 0 not in self.units
                    and native_library._MODE != "sympy" and hasattr(native_library._kernel(), "atlas_jet_abi")):
                from .affine_kernel import _request, _ring, _sparse_expression
                ring = _ring(self.variables)
                rows = _request(["affine_jet", ring.header, str(order),
                                 " ".join(str(self.variables.index(c)) for c in self.coords), ring.text(f)])
                self._jets[key] = tuple(dict.fromkeys((f, *(_sparse_expression(self.variables, r) for r in rows[1:]))))
                if native_library.CHECK and self._jets[key] != self._jet_reference(f, order):
                    raise AssertionError("The native affine jet differs from iterated differentiation.")
            else:
                self._jets[key] = self._jet_reference(f, order)
        return self._jets[key]

    def _jet_reference(self, f, order):
        found, layer = [f], [f]
        for _ in range(order - 1):
            layer = list(dict.fromkeys(d for g in layer for k in self.coords
                                       if not self.vanishes(d := self.derivative(g, k))))
            found.extend(layer)
            if not layer:
                break
        return tuple(dict.fromkeys(found))

    def empty(self, *gens):
        return self._empty_on(gens, self.units)

    def inside(self, unit, gens):
        """Whether the zero set of the ideal lies in that of `unit`, on N."""
        return self._empty_on(tuple(gens), (*self.units, unit))

    def _empty_on(self, gens, units):
        key = (gens, units)
        if key not in self._empty:
            self._empty[key] = frame_locus(self.variables, (*self.rows, *gens), units)
        return self._empty[key]

    def restricted(self, z, k, unit):
        """The submanifold z = 0 of N, where D_k z is invertible, on the open set unit != 0."""
        return Frame(self.variables, tuple(c for c in self.coords if c != k), (*self.rows, z),
                     (*self.units, unit), self.solved)

    def eliminated(self, z, k, coefficients=None):
        """The submanifold z = 0 when z = a*k + b and a is invertible: k = -b/a
        there. Returns the frame without k and the map taking a function to a
        polynomial that is a unit times its restriction (the numerator)."""
        a, b = frame_linear(self.variables, z, k) if coefficients is None else coefficients

        def move(f):
            return frame_restrict(self.variables, f, k, a, b)

        rows = tuple(g for g in map(move, self.rows) if g != 0)
        return Frame(tuple(v for v in self.variables if v != k), tuple(c for c in self.coords if c != k), rows,
                     (*map(move, self.units), a), (*self.solved, z)), move

    def changed(self, swap):
        """The same submanifold after a substitution of the coordinates."""
        def move(gens, variables):
            return tuple(frame_function(variables, chart_expressions(variables).sympify(g).xreplace(swap)) for g in gens)
        # Saved graph equations still use the eliminated coordinates.
        extra = set().union(*(g.free_symbols for g in self.solved)) - set(self.variables)
        original = (*self.variables, *sorted(extra, key=chart_expressions(self.variables).default_sort_key))
        return Frame(self.variables, self.coords, move(self.rows, self.variables),
                     move(self.units, self.variables), move(self.solved, original))


@dataclass(frozen=True)
class State:
    frame: Frame
    coll: tuple      # (exponents of new divisors, function, weight)
    extra: tuple     # equations of the divisors old at this level: weight 1, added after maximal contact
    new: tuple       # (label, variable) of the divisors that are not old so far
    locus: tuple     # equations of the points where the invariant has the prefix so far
    working: tuple   # ideals; the invariant is maximised over the union of their zero sets
    prefix: tuple
    undo: tuple      # substitutions that bring back the original coordinates


@dataclass(frozen=True)
class Found:
    value: tuple
    key: tuple
    centre: tuple    # equations of the locus inside the submanifold of the state
    state: State


class _Context:
    def __init__(self, records, births, fixed, deadline):
        self.records, self.births, self.fixed, self.deadline = records, list(births), set(fixed), deadline

    def check(self):
        if self.deadline is not None and monotonic() > self.deadline:
            raise GiveUp("The time allowed for the blowups is over.")

    def key(self, labels):
        """The order on sets of divisors: lexicographic on membership, oldest divisor first [BM, 1.17]."""
        return tuple(int(label in labels) for label in self.births)


def _older(record, prefix):
    """Whether a divisor is old for the truncation `prefix` of the invariant:
    it was given at the start, or the centre that created it had a larger truncation."""
    return record is None or tuple(record[:len(prefix)]) > tuple(prefix)


def _divide(frame, f, x):
    """A function q on N with f = x*q on N, up to a function without zeros,
    or None when x does not divide f there.

    N is the part of V(rows) where the product u of the units is invertible,
    and x is the coordinate of a divisor of N. The functions on N are the
    polynomials modulo the rows with powers of u as denominators.

    Whether x divides f: f lies in x*O(N) exactly when f*u^k lies in
    I0 = (rows) + (x) for some k, that is, f lies in I0 : u^infinity. In
    that test u may be replaced by its normal form modulo I0.

    The quotient: let J = (rows) + (t*x - 1), with t compared first. If
    f = x*q on N, write q = Q/u^k; then (f*u^k - x*Q)*u^m lies in (rows) for
    some m, so t*f*u^(k+m) is congruent to Q*u^m modulo J and its normal form
    has no t. Conversely, if the normal form p of t*f*u^K has no t, then
    f*u^K - x*p lies in J and has no t, so it vanishes on every component of
    V(rows) not inside x = 0, hence on N: f = x*(p/u^K) there. So p is found
    by trying K = 0, 1, ...; it differs from the quotient by the unit u^K,
    which changes neither orders nor loci. No basis contains the units,
    which are large polynomials.
    """
    if not frame.rows:
        return frame_quotient(frame.variables, f, x)
    first, second = frame.cut(x)
    if second is False:
        return None  # x has no zero on N
    if not first.contains(f) and (second is None or not second.contains(f)):
        return None
    t, basis = frame.over(x)
    g = frame.reduced(f)
    for _ in range(12):
        q = basis.reduce(frame_function((t, *frame.variables), t*g))[1]
        if t not in q.free_symbols:
            return q
        g = frame.reduced(g*frame.unit())
    raise GiveUp("A quotient by the equation of a divisor was not found.")


def _settle(element, frame, variables, through, new):
    """Move into the function the powers of the divisors that become old.
    Those through the locus need integral exponents: (h, mu) is replaced by
    (h^k, k*mu) [BM, Remark 2.8]. The others are units near the locus."""
    exps, poly, weight = element
    power = lcm(*(Fraction(exps.get(h, 0)).denominator for h in through)) if through else 1
    factor = chart_expressions(frame.variables).prod((variables[h]**int(exps.get(h, 0)*power) for h in through))
    kept = tuple((h, e*power) for h, e in exps.items() if h in new and e)
    return dict(kept), frame_function(frame.variables, poly**power*factor), weight*power


def _remove_coordinate_powers(frame, poly, divisors):
    """Return all orders on free coordinate hyperplanes and their joint residual."""
    from .affine_kernel import _request, _ring, _sparse_expression
    from .native_library import CHECK, _MODE, _kernel
    divisors = tuple(divisors)
    def iterated():
        residual = poly
        orders = []
        for v in divisors:
            order = 0
            while (quotient := _divide(frame, residual, v)) is not None:
                residual, order = quotient, order + 1
            orders.append(order)
        return orders, residual
    if frame.rows or _MODE == "sympy" or not hasattr(_kernel(), "atlas_residual_abi"):
        return iterated()
    ring = _ring(frame.variables)
    rows = _request(["coordinate_residual", ring.header,
                     " ".join(str(frame.variables.index(v)) for v in divisors), ring.text(poly)])
    answer = list(map(int, rows[:-1])), _sparse_expression(frame.variables, rows[-1])
    if CHECK and answer != iterated():
        raise AssertionError("Coordinate orders differ from repeated exact division.")
    return answer


def _level(st, ctx):
    """The divisors that are old at this level, then maximal contact and the residual order."""
    ctx.check()
    frame, new = st.frame, dict(st.new)

    def here(gens):
        return any(not frame.empty(*st.locus, *gens, *w) for w in st.working)

    old = [h for h in new if _older(ctx.records.get(h), st.prefix)]
    through = [h for h in old if here((new[h],))]
    subsets = [()]
    for size in range(len(through), 0, -1):
        found = [chosen for chosen in combinations(through, size) if here(tuple(new[h] for h in chosen))]
        if found:
            subsets = found
            break
    out = []
    for chosen in subsets:
        locus = (*st.locus, *(new[h] for h in chosen))
        working = tuple(w for w in st.working if not frame.empty(*locus, *w))
        rest = {h: v for h, v in new.items() if h not in old}
        # Maximal contact is taken for the collection alone; the equations of the
        # divisors old at this level are then added on it, with weight 1
        # [BM, 3.2 and Remark 3.6].
        coll = tuple(_settle(element, frame, new, chosen, rest) for element in st.coll)
        start = replace(st, coll=coll, extra=tuple(new[h] for h in chosen), new=tuple(rest.items()), locus=locus,
                        working=working, prefix=(*st.prefix, len(chosen)))
        # A hypersurface of maximal contact chosen here need not be the transform of
        # the one of the year of birth, and the presentation on it may have no
        # maximal contact of its own that is transverse to the new divisors:
        # then another choice is made here.
        banned = set()
        while True:
            part, choice = [], None
            try:
                for piece, choice in _contact(start, ctx, banned):
                    part.extend(_residual(piece, ctx))
                    choice = None
            except NoContact:
                if choice is None or choice in banned:
                    raise
                banned.add(choice)
                continue
            out.extend(part)
            break
    return out


def _contact(st, ctx, banned=frozenset()):
    """Cover the locus by open sets with a hypersurface of maximal contact, and
    pass to the coefficient collection on it [BM, 5.12, 5.13]. Yields the
    state on each open set with the choice made (which the caller may ban)."""
    remaining = list(st.working)
    current, attempts = st, 0
    while remaining:
        ctx.check()
        frame, new = current.frame, dict(current.new)
        ranked = sorted(enumerate(current.coll), key=lambda item: (item[1][2], len(item[1][0]), chart_expressions(frame.variables).count_ops(item[1][1])))
        for index, (exps, poly, weight) in ranked:
            if weight.denominator != 1 or weight < 1 or frame.vanishes(poly):
                continue
            monomial = chart_expressions(frame.variables).prod((new[h] for h, e in exps.items() if e > 0 and h in new))
            for k in frame.coords:
                if (index, k, attempts) in banned:
                    continue
                # The direction must be complementary to the new divisors through
                # the point [BM, 5.12]: the coordinate of a new divisor serves
                # only off that divisor, where the divisor is no longer counted.
                absent = {h for h, v in new.items() if v == k}
                z = poly
                for _ in range(int(weight) - 1):
                    z = frame.derivative(z, k)
                top = frame.derivative(z, k)
                if frame.vanishes(top):
                    continue
                unit = frame_function(frame.variables, top*monomial*(k if absent else 1))
                hit = [w for w in remaining if not frame.inside(unit, (*current.locus, *w))]
                if not hit:
                    continue
                if not frame.rows and (coefs := frame_linear(frame.variables, z, k)) is not None:
                    inside, move = frame.eliminated(z, k, coefs)
                    inside = Frame(inside.variables, inside.coords, inside.rows,
                                   (*inside.units, move(monomial), *((move(k),) if absent else ())), inside.solved)
                else:
                    inside = frame.restricted(z, k, unit)

                    def move(f):
                        return frame_function(inside.variables, f)
                coll = []
                for e, p, w in current.coll:
                    e = {h: x for h, x in e.items() if h not in absent}
                    for q in range(ceil(w)):
                        moved = move(p)
                        if not inside.vanishes(moved):
                            coll.append((e, moved, w - q))
                        p = frame.derivative(p, k)

                def ideal(gens):
                    return tuple(g for g in map(move, gens) if g != 0)

                coll.extend(({}, g, Fraction(1)) for g in ideal(current.extra) if not inside.vanishes(g))
                yield replace(current, frame=inside, coll=tuple(coll), extra=(), locus=ideal(current.locus),
                              new=tuple((h, v) for h, v in current.new if h not in absent),
                              working=tuple(ideal(w) for w in hit)), (index, k, attempts)
                remaining = [w for w in remaining if w not in hit] + [(*w, unit) for w in hit]
                remaining = [w for w in remaining if not frame.empty(*current.locus, *w)]
                if not remaining:
                    return
        # Some point has no pure derivative of the right order that is not zero:
        # change the complementary coordinates linearly, which gives a general direction.
        attempts += 1
        free = [c for c in frame.coords if c not in ctx.fixed]
        bases = [c for c in frame.coords if c not in new.values()]
        if attempts > 8 or not bases or len(free) < 1:
            raise NoContact("No hypersurface of maximal contact was found.")
        base = bases[(attempts - 1) % len(bases)]
        swap = {c: c + ((attempts + i) % 3 + 1)*(-1)**i*base for i, c in enumerate(free) if c != base}
        if not swap:
            continue
        back = {c: c - (value - c) for c, value in swap.items()}

        def move(gens):
            return tuple(frame_function(frame.variables, chart_expressions(frame.variables).sympify(g).xreplace(swap)) for g in gens)

        current = replace(current, frame=frame.changed(swap),
                          coll=tuple((e, frame_function(frame.variables, p.xreplace(swap)), w) for e, p, w in current.coll),
                          extra=move(current.extra),
                          locus=move(current.locus), working=tuple(move(w) for w in current.working),
                          undo=(*current.undo, back))
        remaining = [move(w) for w in remaining]


def _groups(st):
    """Split the working set according to the functions of the collection that
    vanish identically on N near its points: these impose no condition there.
    Yields (working, collection). On an open set of affine space a nonzero
    polynomial vanishes identically nowhere."""
    frame = st.frame
    if not frame.rows:
        yield st.working, [item for item in st.coll if item[1] != 0]
        return

    def alive(ideals):
        return [w for w in ideals if not frame.empty(*st.locus, *w)]

    def go(work, pending, kept):
        if not pending:
            yield tuple(work), kept
            return
        item, rest = pending[0], pending[1:]
        if frame.vanishes(item[1]):
            yield from go(work, rest, kept)
            return
        # The closure of the part of N where the function is not zero.
        support = saturate(frame.variables, frame.rows, item[1])
        on = alive([(*w, *support) for w in work])
        off = alive([tuple(saturate(frame.variables, (*frame.rows, *st.locus, *w), g)) for w in work for g in support])
        if any(not frame.empty(*st.locus, *w, *support) for w in off):
            raise GiveUp("A function vanishes identically near only part of a locus.")
        if on:
            yield from go(on, rest, [*kept, item])
        if off:
            yield from go(off, rest, kept)

    yield from go(list(st.working), list(st.coll), [])


def _residual(st, ctx):
    """The residual order nu and its maximum locus; then the next level, or the centre."""
    out = []
    for working, coll in _groups(st):
        if not coll:
            # The locus is N near these points [BM, 3.2]; the equations of the
            # locus so far remove the other parts of N.
            out.append(Found((*st.prefix, INFINITE), (), st.locus, replace(st, working=working)))
        else:
            out.extend(_residue(replace(st, working=working, coll=tuple(coll)), ctx))
    return out


def _residue(st, ctx):
    ctx.check()
    frame, new = st.frame, dict(st.new)

    def here(gens):
        return any(not frame.empty(*st.locus, *gens, *w) for w in st.working)

    live = [h for h in new if here((new[h],))]
    # Each function is written x^e * g with g not divisible by a new divisor.
    normal = []
    for exps, poly, weight in st.coll:
        exps = {h: Fraction(exps.get(h, 0)) for h in live}
        if live:
            orders, poly = _remove_coordinate_powers(frame, poly, (new[h] for h in live))
            for h, order in zip(live, orders):
                exps[h] += order
        normal.append((exps, poly, weight))
    from .centre_weights import Presentation
    alpha, *residual = Presentation(live, normal).residual()
    rest = [(e, p, w) for e, (_, p, w) in zip(residual, normal)]
    table = Presentation(live, rest)
    strata = [chosen for size in range(len(live) + 1) for chosen in combinations(live, size)
              if here(tuple(new[h] for h in chosen))]
    positions = {h: j for j, h in enumerate(live)}
    indices = [tuple(positions[h] for h in chosen) for chosen in strata]

    def conditions(value):
        for chosen, required in zip(strata, table.requirements(indices, value)):
            gens = [new[h] for h in chosen]
            for (_, p, _), need in zip(rest, required):
                if need >= 1:
                    gens.extend(frame.jet(p, need))
            yield tuple(gens)

    bounds = []
    for chosen in strata:
        divisor = tuple(new[h] for h in chosen)
        orders = []
        for _, p, _ in rest:
            order = 0
            while here((*divisor, *frame.jet(p, order + 1))):
                order += 1
                if order > 64:
                    raise GiveUp("An order is beyond the limit.")
            orders.append(order)
        bounds.append(orders)
    values = table.candidate_values(indices, bounds)
    low, high = 0, len(values) - 1     # the locus of values[low] is not empty
    while low < high:
        ctx.check()
        middle = (low + high + 1)//2
        if any(here(gens) for gens in conditions(values[middle])):
            low = middle
        else:
            high = middle - 1
    value = values[low]
    if value == 0:
        # The monomial case: the locus is the union of the N meet H_I [BM, (3.2)].
        sets = [chosen for size in range(1, len(live) + 1) for chosen in combinations(live, size)
                if sum(alpha[h] for h in chosen) >= 1 and here(tuple(new[h] for h in chosen))]
        sets = [chosen for chosen in sets if not any(set(other) < set(chosen) for other in sets)]
        if not sets:
            raise GiveUp("The monomial part of a presentation has order less than one.")
        chosen = max(sets, key=ctx.key)
        return [Found((*st.prefix, Fraction(0)), ctx.key(chosen), (*st.locus, *(new[h] for h in chosen)), st)]
    coll = [(e, p, w*value) for e, p, w in rest]
    if value < 1:
        coll.append((dict(alpha), chart_expressions(frame.variables).sympify(1), 1 - value))
    out = []
    for gens in conditions(value):
        working = tuple(w for w in st.working if not frame.empty(*st.locus, *gens, *w))
        if working:
            out.extend(_level(replace(st, coll=tuple(coll), locus=(*st.locus, *gens), working=working,
                                      prefix=(*st.prefix, value)), ctx))
    return out


def _principal(variables, ambient, ideal):
    """A single generator of the ideal of a divisor on the chart."""
    gens = [g for g in ideal if not ideal_subset(variables, (g,), ambient)]
    for g in sorted(gens, key=lambda g: (g not in variables, chart_expressions(variables).count_ops(g))):
        if ideal_subset(variables, gens, (*ambient, g)):
            return g
    raise GiveUp("A divisor is not given by one equation on a chart.")


def _same(f):
    return f


def _frames(variables, ambient, dimension, divisors, working, eliminate=False, units=()):
    """Cover the working set by open sets of the chart with coordinates among
    the variables. The variable of a divisor through a point must be one of
    the coordinates there: an open set whose coordinates leave out the
    variable of a divisor is taken off that divisor.

    Yields (frame, ideals of the working set met by the open set). With
    `eliminate` a third item is the map that takes a polynomial in the
    variables of the chart to a function on the frame: when the chart is the
    graph of one equation that is linear in the variable left out, that
    variable is eliminated and derivations on the frame are plain."""
    count = len(variables) - dimension
    if count == 0:
        frame = Frame(variables, variables, (), units)
        yield (frame, list(working), _same) if eliminate else (frame, list(working))
        return
    remaining = list(working)
    gate = frame_function(variables, chart_expressions(variables).prod(units)) if units else None

    def left(w):
        # Only the points where the units given are invertible are to be covered.
        return not empty_locus(variables, (*ambient, *w)) and (
            gate is None or not radical_subset(variables, (gate,), (*ambient, *w)))

    choices = sorted(combinations(variables, count), key=lambda chosen: sum(v in divisors for v in chosen))
    for dependent in choices:
        for rows in combinations(ambient, count):
            minor = frame_minor(variables, rows, dependent)
            if minor == 0:
                continue
            away = frame_function(variables, minor*chart_expressions(variables).prod((v for v in dependent if v in divisors))*chart_expressions(variables).prod(units))
            hit = [w for w in remaining if not radical_subset(variables, (away,), (*ambient, *w))]
            if not hit:
                continue
            frame = Frame(variables, tuple(v for v in variables if v not in dependent), rows, (away,))
            if not eliminate:
                yield frame, hit
            elif count == 1 and len(ambient) == 1 and (coefs := frame_linear(variables, rows[0], dependent[0])) is not None:
                inside, move = Frame(variables, variables).eliminated(rows[0], dependent[0], coefs)
                off = (move(dependent[0]),) if dependent[0] in divisors else ()
                yield Frame(inside.variables, inside.coords, inside.rows, (*inside.units, *off, *map(move, units)),
                            inside.solved), hit, move
            else:
                yield frame, hit, _same
            remaining = [w for w in remaining if w not in hit] + [(*w, away) for w in hit]
            remaining = [w for w in remaining if left(w)]
            if not remaining:
                return
    raise GiveUp("No coordinates were found on a chart.")


def _intersection(variables, first, second):
    """The intersection of two ideals."""
    t = chart_expressions(variables).Dummy("t")
    basis = groebner([t*g for g in first] + [(1 - t)*g for g in second], (t, *variables), order="lex")
    return tuple(g for g in basis.exprs if t not in g.free_symbols)


def maximum(variables, ambient, dimension, strict, divisors, working, records, births, deadline=None, away=()):
    """The maximum of the invariant of the hypersurface `strict` over a closed
    set of the chart, and the locus where it is attained.

    `divisors` lists (label, ideal) for the exceptional divisors, `working`
    the ideals whose zero sets make up the closed set, `records` gives for a
    label the invariant of the centre that created the divisor (None for a
    divisor given at the start) and `births` the labels in order of creation.

    Returns (value, key, generators of the ideal of the locus), where key
    orders the components in the monomial case, or None when the hypersurface
    does not meet the set.

    The points of the closed sets V(Z), Z in `away`, are left out of the set:
    the rest is covered by the open sets where a product of one generator of
    each Z is invertible.
    """
    original, chart = tuple(variables), tuple(ambient)
    strict = tuple(g for g in strict if not ideal_subset(original, (g,), chart))
    working = [tuple(w) for w in working if not empty_locus(original, (*chart, *strict, *w))]
    if not working or not strict:
        return None
    # Every divisor through the set must be a coordinate hyperplane: one that is
    # not becomes one on the graph of its equation.
    names, graph = {}, {}
    variables, ambient = original, list(chart)
    for label, ideal in divisors:
        if all(empty_locus(original, (*chart, *ideal, *w)) for w in working):
            continue
        g = _principal(original, chart, ideal)
        if g not in original:
            name = chart_expressions(variables).Dummy(f"divisor_{label}")
            variables, graph[name] = (*variables, name), g
            ambient.append(name - g)
            g = name
        names[label] = g
    ctx = _Context(records, births, names.values(), deadline)
    found = []
    covers = [chart_expressions(variables).sympify(1)]
    for ideal in away:
        if any(not empty_locus(original, (*chart, *strict, *ideal, *w)) for w in working):
            covers = [frame_function(original, u*g) for u in covers for g in ideal]
    pieces, left = [], list(working)
    for unit in dict.fromkeys(covers):
        if unit == 1:
            pieces.append(((), left))
            break
        part = [w for w in left if not radical_subset(original, (unit,), (*chart, *strict, *w))]
        if part:
            pieces.append(((unit,), part))
        left = [w for w in ((*w, unit) for w in left) if not empty_locus(original, (*chart, *strict, *w))]
        if not left:
            break
    frames = [item for units, part in pieces
              for item in _frames(variables, ambient, dimension, tuple(names.values()), part, eliminate=True, units=units)]
    for frame, live, move in frames:
        own = tuple(g for g in map(move, strict) if g != 0)
        live = [tuple(g for g in map(move, w) if g != 0) for w in live]
        # A divisor whose variable has been eliminated does not meet the frame.
        present = tuple((label, v) for label, v in names.items() if v in frame.variables)
        order = 1
        while any(not frame.empty(*(d for g in own for d in frame.jet(g, order + 1)), *w) for w in live):
            order += 1
            if order > 64:
                raise GiveUp("An order is beyond the limit.")
        locus = tuple(d for g in own for d in frame.jet(g, order))
        live = tuple(w for w in live if not frame.empty(*locus, *w))
        coll = tuple(({}, g, Fraction(order)) for g in own)
        found.extend(_level(State(frame, coll, (), present, locus, live, (Fraction(order),), ()), ctx))
    if not found:
        return None
    value, key = max((item.value, item.key) for item in found)
    centre = None
    for item in found:
        if (item.value, item.key) != (value, key):
            continue
        frame = item.state.frame

        def back(gens):
            for swap in reversed(item.state.undo):
                gens = [frame_function(variables, chart_expressions(variables).sympify(g).xreplace(swap)) for g in gens]
            return [g for g in (frame_function(original, chart_expressions(variables).sympify(g).xreplace(graph)) for g in gens) if g != 0]

        # The locus on the open set, then its closure in the chart.
        gens = ideal_basis(original, (*chart, *back((*item.centre, *frame.rows, *frame.solved))))
        for unit in back(frame.units):
            gens = saturate(original, gens, unit)
        gens = ideal_basis(original, gens)
        centre = gens if centre is None or centre == gens else _intersection(original, centre, gens)
    return value, key, tuple(centre)
