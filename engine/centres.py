"""The centre of blowing up: the maximum locus of the invariant of Bierstone and Milman.

The setting is a smooth variety W (a chart, given by equations in affine
space), a reduced hypersurface X in it, and a collection E of smooth
divisors with normal crossings: the exceptional divisors so far. The
invariant of X at a point a is a sequence

    inv(a) = (nu_1(a), s_1(a); nu_2(a), s_2(a); ...; nu_{t+1}(a)),

compared lexicographically, whose last term is 0 or infinity. It is defined
in E. Bierstone and P. Milman, Canonical desingularization in characteristic
zero by blowing up the maximum strata of a local invariant, Invent. Math.
128 (1997), and, in the form followed here, in their Desingularization
algorithms I. Role of exceptional divisors, Moscow Math. J. 3 (2003),
sections 1.5, 2.4, 2.6, 3.2 and 5.2 (cited below as [BM]).

  - nu_1(a) is the order of X at a.
  - A divisor H of E through a is old at level r when it was created before
    the truncation (nu_1, s_1, ..., nu_r) of the invariant took, along the
    images of a, the value it has at a. A divisor is created by blowing up a
    centre on which the invariant is constant, and the invariant never
    increases along the images of a point, so this happens exactly when the
    truncation of the invariant of that centre is larger than the truncation
    at a. The divisors given at the start are old at level 1. s_r(a) is the
    number of divisors through a that are old at level r and not before.
  - A presentation at level r is a submanifold N (maximal contact), a
    collection of functions h on N with weights mu_h, with order at least
    mu_h on the locus, and the divisors that are still new. It starts with
    N = W and the generators of the ideal of X, of weight nu_1.
  - Maximal contact [BM, 5.12, 5.13]: if some f of integral weight d has
    order exactly d, a derivative z of f of order d-1 in directions
    complementary to the new divisors has order 1; the next N is z = 0, and
    the collection becomes the derivatives of order q < mu_h of every h in
    such a direction, restricted to z = 0, with weights mu_h - q. (Lemma 5.4
    of [BM]: these conditions are those of the old collection.) The
    equations of the divisors old at this level are added with weight 1.
  - mu = min ord(h)/mu_h, and mu_H is the same with the order along a new
    divisor H. The residual order is nu_{r+1} = mu - sum of the mu_H over
    the new divisors through the point [BM, (3.1)]. With D the product of
    the x_H^mu_H, the next collection consists of the h/D^mu_h with weights
    mu_h*nu_{r+1}, and of D with weight 1 - nu_{r+1} when this is positive
    [BM, (2.3)].
  - If the collection vanishes on N, nu_{r+1} is infinite and the locus of
    the invariant is N. If nu_{r+1} = 0, the locus is the union of the
    N meet H_I over the minimal sets I of new divisors with sum of the mu_H
    at least 1 [BM, (3.2)], and one of them is selected by a fixed order on
    the sets of divisors [BM, 1.17].

Theorem 1.14 of [BM]: the invariant is upper semicontinuous, does not
increase under blowups whose centre is a locus on which it is constant,
that locus is smooth with normal crossings with E, the invariant decreases
over the centre, and every nonincreasing sequence of values stabilises.
Hence any sequence of such blowups is finite, and it ends with X smooth and
with normal crossings with E.

What is computed here is the maximum of the invariant over a closed set of
points of X (the points where normal crossings fail), and the locus where
it is attained. The definitions are local, with choices (coordinates,
maximal contact) valid on open sets; the chart is covered by such open
sets, an open set u != 0 being the closed set t*u = 1 with one more
variable. The values do not depend on the choices. Derivations of a
submanifold N of affine space are obtained by implicit differentiation: if
the equations g_1, ..., g_c of N have invertible Jacobian determinant M in
the variables y, the other variables x are coordinates on N, and

    D_k f = det d(g_1, ..., g_c, f)/d(y, x_k) = M * (df/dx_k on N).

Orders are computed with the D_k: M is a unit, and the ideal generated by
the iterated D of order < m is the one generated by the derivatives.
"""
