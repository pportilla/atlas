INFINITE = float("inf")


class GiveUp(Exception):
    """The procedure cannot continue; nothing is claimed."""


class NoContact(GiveUp):
    """No hypersurface of maximal contact was found for a presentation."""


@dataclass(frozen=True)
class State:
    frame: Frame
    coll: tuple      # (exponents of new divisors, function, weight)
    extra: tuple     # equations of the divisors old at this level: weight 1, added after maximal contact
    new: tuple       # (label, variable) of the divisors that are not old so far
    locus: tuple     # equations of the points where the invariant has the prefix so far
    working: tuple   # ideals; the invariant is maximised over the union of their zero sets
    prefix: tuple
    undo: tuple      # substitutions that bring back the original coordinates


@dataclass(frozen=True)
class Found:
    value: tuple
    key: tuple
    centre: tuple    # equations of the locus inside the submanifold of the state
    state: State


class _Context:
    def __init__(self, records, births, fixed, deadline):
        self.records, self.births, self.fixed, self.deadline = records, list(births), set(fixed), deadline

    def check(self):
        if self.deadline is not None and monotonic() > self.deadline:
            raise GiveUp("The time allowed for the blowups is over.")


def _settle(element, frame, variables, through, new):
    """Move into the function the powers of the divisors that become old.
    Those through the locus need integral exponents: (h, mu) is replaced by
    (h^k, k*mu) [BM, Remark 2.8]. The others are units near the locus."""
    exps, poly, weight = element
    keys = tuple(dict.fromkeys((*exps, *through)))
    updated = level_weights("settle", [weight], exponents=[rational_text(exps.get(h, 0)) for h in keys],
                            through=[keys.index(h) for h in through])
    power = integer_from_decimal(updated["power"])
    scaled = dict(zip(keys, map(coordinate_fraction, updated["exponents"])))
    factor = chart_expressions(frame.variables).prod((variables[h]**int(scaled[h]) for h in through))
    kept = {h: e for h, e in scaled.items() if h in new and e}
    return kept, frame_function(frame.variables, poly**power*factor), coordinate_fraction(updated["weight"])


def _remove_coordinate_powers(frame, poly, divisors):
    """Return all orders on free coordinate hyperplanes and their joint residual."""
    from .affine_kernel import _request, _ring, _sparse_expression
    divisors = tuple(divisors)
    if frame.rows and not frame.known_scalar_unit(poly):
        from .field_wide import _expanded_row
        lines = frame._implicit_input(poly)
        lines.extend((_expanded_row(frame.variables,frame.unit()), str(len(divisors))))
        for v in divisors:
            cut, localized = frame.cut(v)
            if localized is False:
                lines.append("absent")
                continue
            t, over = frame.over(v)
            lines.extend(("present", *frame._basis_lines(frame.variables,cut)))
            lines.extend(("0",) if localized is None else frame._basis_lines(frame._cut_coordinates[v],localized))
            lines.extend(frame._basis_lines((t,*frame.variables),over))
        rows = _request(["implicit_coordinates", *lines])
        if rows == ["quotient_unavailable"]:
            raise GiveUp("A quotient by the equation of a divisor was not found.")
    else:
        ring = _ring(frame.variables)
        rows = _request(["coordinate_residual", ring.header,
                         " ".join(str(frame.variables.index(v)) for v in divisors), ring.text(poly)])
    answer = list(map(integer_from_decimal, rows[:-1])), _sparse_expression(frame.variables, rows[-1])
    return answer


def _level(st, ctx):
    """The divisors that are old at this level, then maximal contact and the residual order."""
    ctx.check()
    frame, new = st.frame, dict(st.new)

    def here(gens):
        return any(not frame.empty(*st.locus, *gens, *w) for w in st.working)

    labels = tuple(new)
    records = [None if (record := ctx.records.get(h)) is None else invariant_row(record[:len(st.prefix)])
               for h in labels]
    indices = level_weights("old_divisors", (), records=records, prefix=invariant_row(st.prefix))
    old = [labels[i] for i in indices]
    through = [h for h in old if here((new[h],))]
    subsets = divisor_subsets(through, lambda labels: here(tuple(new[h] for h in labels)), largest=True)
    out = []
    for chosen in subsets:
        locus = (*st.locus, *(new[h] for h in chosen))
        working = tuple(w for w in st.working if not frame.empty(*locus, *w))
        rest = {h: v for h, v in new.items() if h not in old}
        # Maximal contact is taken for the collection alone; the equations of the
        # divisors old at this level are then added on it, with weight 1
        # [BM, 3.2 and Remark 3.6].
        coll = tuple(_settle(element, frame, new, chosen, rest) for element in st.coll)
        start = replace(st, coll=coll, extra=tuple(new[h] for h in chosen), new=tuple(rest.items()), locus=locus,
                        working=working, prefix=(*st.prefix, len(chosen)))
        # A hypersurface of maximal contact chosen here need not be the transform of
        # the one of the year of birth, and the presentation on it may have no
        # maximal contact of its own that is transverse to the new divisors:
        # then another choice is made here.
        banned = set()
        while True:
            part, choice = [], None
            try:
                for piece, choice in _contact(start, ctx, banned):
                    part.extend(_residual(piece, ctx))
                    choice = None
            except NoContact:
                if choice is None or choice in banned:
                    raise
                banned.add(choice)
                continue
            out.extend(part)
            break
    return out


def _contact(st, ctx, banned=frozenset()):
    """Cover the locus by open sets with a hypersurface of maximal contact, and
    pass to the coefficient collection on it [BM, 5.12, 5.13]. Yields the
    state on each open set with the choice made (which the caller may ban)."""
    remaining = list(st.working)
    current, attempts = st, 0
    while remaining:
        ctx.check()
        yielded = False
        frame, new = current.frame, dict(current.new)
        ranks = [invariant_row((w, len(e), chart_expressions(frame.variables).count_ops(p))) for e,p,w in current.coll]
        ranked = level_weights("candidate_order", [w for _,_,w in current.coll], ranks=ranks, integral_weight=True)
        for index in ranked:
            exps, poly, weight = current.coll[index]
            if frame.vanishes(poly):
                continue
            names = [h for h in exps if h in new]
            candidate = level_weights("contact_candidate", [weight], exponents=[rational_text(exps[h]) for h in names])
            factors = tuple(new[names[i]] for i in candidate["support"])
            monomial = chart_expressions(frame.variables).prod(factors)
            degree = integer_from_decimal(candidate["degree"])
            points = None
            if frame.rows and candidate["probe_direction"]:
                # A finite superset suffices to rule out a direction. Try the
                # working pieces before adding the previous differential ideals.
                points = frame.working_points((), remaining)
                if points is None:
                    points = frame.working_points(current.locus, remaining)
            for k in frame.coords:
                if (index, k, attempts) in banned:
                    continue
                # The direction must be complementary to the new divisors through
                # the point [BM, 5.12]: the coordinate of a new divisor serves
                # only off that divisor, where the divisor is no longer counted.
                absent = {h for h, v in new.items() if v == k}
                if points is not None:
                    active = frame.contact_open_points(points, (*factors, k) if absent else factors)
                    if not active or frame.direction_vanishes(poly, k, degree, active):
                        continue
                chain = frame.derivative_chain(poly, k, degree)
                z, top = chain[-2:]
                if frame.vanishes(top):
                    continue
                unit = frame_function(frame.variables, top*monomial*(k if absent else 1))
                hit = [w for w in remaining if not frame.inside(unit, (*current.locus, *w))]
                if not hit:
                    continue
                if not frame.rows and (coefs := frame_linear(frame.variables, z, k)) is not None:
                    inside, move = frame.eliminated(z, k, coefs)
                    inside = Frame(inside.variables, inside.coords, inside.rows,
                                   (*inside.units, move(monomial), *((move(k),) if absent else ())), inside.solved)
                else:
                    inside = frame.restricted(z, k, unit, witness_loci=((*current.locus, *w) for w in hit),
                                              working=hit)

                    def move(f):
                        return frame_function(inside.variables, f)
                coll = []
                marks = level_weights("contact", [w for _, _, w in current.coll])
                for (e, p, _), row_marks in zip(current.coll, marks):
                    e = {h: x for h, x in e.items() if h not in absent}
                    if p == poly and len(row_marks) <= len(chain):
                        derivatives = chain
                    else:
                        derivatives = frame.derivative_chain(p, k, len(row_marks) - 1)
                    for derivative, mark in zip(derivatives, row_marks):
                        moved = move(derivative)
                        if not inside.vanishes(moved):
                            coll.append((e, moved, coordinate_fraction(mark)))

                def ideal(gens):
                    return tuple(g for g in map(move, gens) if g != 0)

                coll.extend(({}, g, Fraction(1)) for g in ideal(current.extra) if not inside.vanishes(g))
                yielded = True
                yield replace(current, frame=inside, coll=tuple(coll), extra=(), locus=ideal(current.locus),
                              new=tuple((h, v) for h, v in current.new if h not in absent),
                              working=tuple(ideal(w) for w in hit)), (index, k, attempts)
                remaining = [w for w in remaining if w not in hit] + [(*w, unit) for w in hit]
                remaining = [w for w in remaining if not frame.empty(*current.locus, *w)]
                if not remaining:
                    return
        # Some point has no pure derivative of the right order that is not zero:
        # change the complementary coordinates linearly, which gives a general direction.
        attempts += 1
        free = [c for c in frame.coords if c not in ctx.fixed]
        bases = [c for c in frame.coords if c not in new.values()]
        if attempts > 8 or not bases or len(free) < 1:
            raise NoContact("No hypersurface of maximal contact was found.")
        # With one free coordinate that is the only base every shear is empty. An
        # attempt that yielded nothing, with no choice banned for it, then repeats
        # in every later attempt, which may try only fewer choices.
        if not yielded and len(free) == 1 and bases == free and not any(c[2] == attempts - 1 for c in banned):
            raise NoContact("No hypersurface of maximal contact was found.")
        shear = level_weights("contact_shear", (), attempt=attempts, free=len(free), bases=len(bases))
        base = bases[shear["base"]]
        swap = {c: c + coefficient*base for c, coefficient in zip(free,shear["coefficients"]) if c != base}
        if not swap:
            continue
        back = {c: c - (value - c) for c, value in swap.items()}

        def move(gens):
            return tuple(frame_function(frame.variables, chart_expressions(frame.variables).sympify(g).xreplace(swap)) for g in gens)

        current = replace(current, frame=frame.changed(swap),
                          coll=tuple((e, frame_function(frame.variables, p.xreplace(swap)), w) for e, p, w in current.coll),
                          extra=move(current.extra),
                          locus=move(current.locus), working=tuple(move(w) for w in current.working),
                          undo=(*current.undo, back))
        remaining = [move(w) for w in remaining]


def _groups(st):
    """Split the working set according to the functions of the collection that
    vanish identically on N near its points: these impose no condition there.
    Yields (working, collection). On an open set of affine space a nonzero
    polynomial vanishes identically nowhere."""
    frame = st.frame
    if not frame.rows:
        yield st.working, [item for item in st.coll if item[1] != 0]
        return

    def distinct(ideals, *, check_empty=False):
        pieces = tuple(dict.fromkeys(ideals))
        if check_empty:
            pieces = tuple(w for w in pieces if not frame.empty(*st.locus, *w))
        if len(pieces) < 2:
            return pieces
        # A piece is used only on this frame and invariant locus. Equal
        # reduced bases there give equal restrictions on every smaller open.
        # Keep the original equations when passing a piece to the next level.
        representatives = {}
        for w in pieces:
            basis = ideal_basis(frame.variables, (*frame.rows, *st.locus, *w))
            representatives.setdefault(basis, w)
        return tuple(representatives.values())

    ideals, indices = [], {}
    def pack(work):
        rows = []
        for w in work:
            if w not in indices:
                indices[w] = len(ideals)
                ideals.append(w)
            rows.append(indices[w])
        return rows

    def query(task):
        f = st.coll[task["i"]][1]
        operation = task["query"]
        if operation == "regular":
            return frame.graph_regular(f)
        if operation == "vanishes":
            return frame.vanishes(f)
        work = tuple(ideals[i] for i in task["work"])
        if operation == "working_orders":
            points = frame.working_points((), work)
            if points is None and st.locus:
                points = frame.working_points(st.locus, work)
            return None if points is None else [frame.point_order(f, p) for p in points]
        if operation == "live":
            return pack(w for w in work if not frame.empty(*st.locus, *w))
        # Only the zero sets of these pieces matter, so the cheaper grevlex
        # bases serve (native/centre_maximum.cpp does the same).
        support = saturate_grevlex(frame.variables, frame.rows, f)
        on = distinct(((*w, *support) for w in work), check_empty=True)
        off = distinct((tuple(saturate_grevlex(frame.variables, (*frame.rows, *st.locus, *w), g))
                        for w in work for g in support), check_empty=True)
        return dict(on=pack(on), off=pack(off),
                    overlap=any(not frame.empty(*st.locus, *w, *support) for w in off))

    groups = centre_search("grouped_loci", query, work=pack(distinct(st.working)), count=len(st.coll))
    if groups is None:
        raise GiveUp("A function vanishes identically near only part of a locus.")
    for work, selected in groups:
        yield tuple(ideals[i] for i in work), [st.coll[i] for i in selected]


def _residual(st, ctx):
    """The residual order nu and its maximum locus; then the next level, or the centre."""
    out = []
    for working, coll in _groups(st):
        if not coll:
            # The locus is N near these points [BM, 3.2]; the equations of the
            # locus so far remove the other parts of N.
            out.append(Found((*st.prefix, INFINITE), (), st.locus, replace(st, working=working)))
        else:
            out.extend(_residue(replace(st, working=working, coll=tuple(coll)), ctx))
    return out


def _residue(st, ctx):
    ctx.check()
    frame, new = st.frame, dict(st.new)

    def here(gens):
        return any(not frame.empty(*st.locus, *gens, *w) for w in st.working)

    live = [h for h in new if here((new[h],))]
    # Each function is written x^e * g with g not divisible by a new divisor.
    normal = []
    for exps, poly, weight in st.coll:
        exps = {h: Fraction(exps.get(h, 0)) for h in live}
        if live:
            orders, poly = _remove_coordinate_powers(frame, poly, (new[h] for h in live))
            adjusted = level_weights("add_orders", exps.values(), orders=list(map(integer_text, orders)))
            exps = dict(zip(live, map(coordinate_fraction, adjusted)))
        normal.append((exps, poly, weight))
    alpha, *residual = Presentation(live, normal).residual()
    rest = [(e, p, w) for e, (_, p, w) in zip(residual, normal)]
    table = Presentation(live, rest)
    strata = divisor_subsets(live, lambda labels: here(tuple(new[h] for h in labels)))
    positions = {h: j for j, h in enumerate(live)}
    indices = [tuple(positions[h] for h in chosen) for chosen in strata]

    def conditions(value):
        for chosen, required in zip(strata, table.requirements(indices, value)):
            gens = [new[h] for h in chosen]
            for (_, p, _), need in zip(rest, required):
                if need >= 1:
                    gens.extend(frame.jet(p, need))
            yield tuple(gens)

    def point_maximum():
        orders = []
        for chosen, ids in zip(strata, indices):
            ctx.check()
            divisor = tuple(new[h] for h in chosen)
            points = frame.working_points((*st.locus, *divisor), st.working)
            if points is None:
                return None
            for point in points:
                row = [frame.point_order(p, point) for _, p, _ in rest]
                if None in row:
                    return None
                orders.append((ids, row))
        return table.point_maximum(orders) if orders else None

    value = point_maximum() if frame.rows else None
    if value is None:
        bounds = []
        for chosen in strata:
            divisor = tuple(new[h] for h in chosen)
            orders = []
            for _, p, _ in rest:
                orders.append(jet_order(0, lambda k: here((*divisor, *frame.jet(p, k)))))
            bounds.append(orders)
        values = table.candidate_values(indices, bounds)
        def live_threshold(task):
            ctx.check()
            return any(here(gens) for gens in conditions(values[task["i"]]))
        selected = centre_search("maximum_threshold", live_threshold, count=len(values))
        value = values[selected]
    if value == 0:
        # The monomial case: the locus is the union of the N meet H_I [BM, (3.2)].
        minimal = level_weights("monomial", [alpha[h] for h in live], strata=indices)
        sets = [strata[i] for i in minimal]
        if not sets:
            raise GiveUp("The monomial part of a presentation has order less than one.")
        keys = [tuple(key) for key in level_weights("birth_keys", (), births=ctx.births, groups=list(map(list, sets)))]
        index = maximum_indices(((),key) for key in keys)[0]
        chosen = sets[index]
        return [Found((*st.prefix, Fraction(0)), keys[index], (*st.locus, *(new[h] for h in chosen)), st)]
    next_weights = level_weights("next_level", [w for _, _, w in rest], threshold=[rational_text(value)])
    coll = [(e, p, coordinate_fraction(w)) for (e, p, _), w in zip(rest, next_weights["scaled"])]
    if "extra" in next_weights:
        coll.append((dict(alpha), chart_expressions(frame.variables).sympify(1), coordinate_fraction(next_weights["extra"])))
    out = []
    for gens in conditions(value):
        working = tuple(w for w in st.working if not frame.empty(*st.locus, *gens, *w))
        if working:
            out.extend(_level(replace(st, coll=tuple(coll), locus=(*st.locus, *gens), working=working,
                                      prefix=(*st.prefix, value)), ctx))
    return out


def _principal(variables, ambient, ideal):
    """A single generator of the ideal of a divisor on the chart."""
    ranks = [invariant_row((int(g not in variables), chart_expressions(variables).count_ops(g))) for g in ideal]
    selected = level_weights("principal", (), width=len(variables), ranks=ranks,
                             ambient=centre_rows(variables, ambient), ideal=centre_rows(variables, ideal))
    if selected is None:
        raise GiveUp("A divisor is not given by one equation on a chart.")
    return ideal[selected]


def _same(f):
    return f


def _frames(variables, ambient, dimension, divisors, working, eliminate=False, units=()):
    """Cover the working set by open sets of the chart with coordinates among
    the variables. The variable of a divisor through a point must be one of
    the coordinates there: an open set whose coordinates leave out the
    variable of a divisor is taken off that divisor.

    Yields (frame, ideals of the working set met by the open set). With
    `eliminate` a third item is the map that takes a polynomial in the
    variables of the chart to a function on the frame: when the chart is the
    graph of one equation that is linear in the variable left out, that
    variable is eliminated and derivations on the frame are plain."""
    remaining = list(working)
    found = []
    gate = frame_function(variables, chart_expressions(variables).prod(units)) if units else None

    def left(w):
        return not empty_locus(variables, (*ambient, *w)) and (
            gate is None or not radical_subset(variables, (gate,), (*ambient, *w)))

    def query(task):
        nonlocal remaining
        if task["query"] == "affine":
            frame = Frame(variables, variables, (), units)
            found.append((frame, remaining, _same) if eliminate else (frame, remaining))
            return True
        dependent = tuple(variables[j] for j in task["dependent"])
        rows = tuple(ambient[j] for j in task["rows"])
        minor = frame_minor(variables, rows, dependent)
        if minor == 0:
            return False
        products = chart_expressions(variables).prod
        away = frame_function(variables, minor*products(v for v in dependent if v in divisors)*products(units))
        hit = [w for w in remaining if not radical_subset(variables, (away,), (*ambient, *w))]
        if not hit:
            return False
        frame = Frame(variables, tuple(v for v in variables if v not in dependent), rows, (away,))
        if not eliminate:
            found.append((frame, hit))
        elif task["linear"] and (coefs := frame_linear(variables, rows[0], dependent[0])) is not None:
            inside, move = Frame(variables, variables).eliminated(rows[0], dependent[0], coefs)
            off = (move(dependent[0]),) if dependent[0] in divisors else ()
            found.append((Frame(inside.variables, inside.coords, inside.rows, (*inside.units, *off, *map(move, units)),
                                inside.solved), hit, move))
        else:
            found.append((frame, hit, _same))
        remaining = [w for w in remaining if w not in hit] + [(*w, away) for w in hit]
        remaining = [w for w in remaining if left(w)]
        return not remaining

    complete = centre_search("frame_cover", query, width=len(variables), dimension=dimension, equations=len(ambient),
                             divisors=[v in divisors for v in variables])
    if not complete:
        raise GiveUp("No coordinates were found on a chart.")
    yield from found


def _intersection(variables, first, second):
    """The intersection of two ideals."""
    from .kernel import exprs
    rows = level_weights("locus_intersection", (), width=len(variables), first=centre_rows(variables, first),
                         second=centre_rows(variables, second))
    return exprs(variables, rows)


def _affine_maximum(variables, ambient, dimension, strict, divisors, working, records, away):
    """Transport an ordinary chart to the complete native coefficient descent."""
    from . import native_library
    from .kernel import _lines, exprs
    from .kernel_json import kernel_json
    from .native_polynomial import native_ring
    from .polynomial import kernel_fraction

    if (ambient or away or dimension != len(variables) or dimension > 3 or len(strict) != 1
            or len(divisors) > 1 or not native_ring(variables)):
        return None
    scope = native_library.current_replay_scope()
    if scope is not None and scope.compute == "gpu":
        return None
    if not hasattr(native_library._kernel(), "atlas_affine_centre_maximum"):
        return None
    divisor, birth = None, None
    if divisors:
        label, generators = divisors[0]
        divisor = _lines(variables, generators)
        if (record := records.get(label)) is not None:
            birth = invariant_row(record)
    result = kernel_json("atlas_affine_centre_maximum", "maximum", width=dimension,
                         strict=_lines(variables, strict), working=[_lines(variables, w) for w in working],
                         divisor=divisor, birth=birth)
    if result is None:
        return None
    def value(entry):
        if isinstance(entry, int):
            return entry
        return INFINITE if entry == "inf" else kernel_fraction(entry)
    return tuple(map(value, result["value"])), (), exprs(variables, result["ideal"])


def maximum(variables, ambient, dimension, strict, divisors, working, records, births, deadline=None, away=(),
            order_only=False):
    """The maximum of the invariant of the hypersurface `strict` over a closed
    set of the chart, and the locus where it is attained.

    `divisors` lists (label, ideal) for the exceptional divisors, `working`
    the ideals whose zero sets make up the closed set, `records` gives for a
    label the invariant of the centre that created the divisor (None for a
    divisor given at the start) and `births` the labels in order of creation.

    Returns (value, key, generators of the ideal of the locus), where key
    orders the components in the monomial case, or None when the hypersurface
    does not meet the set.

    The points of the closed sets V(Z), Z in `away`, are left out of the set:
    the rest is covered by the open sets where a product of one generator of
    each Z is invertible.

    The kernel computes the whole procedure below in one call
    (native/centre_maximum.cpp); this file's steps answer for rings beyond
    its packed range.
    """
    found = _native_maximum(variables, ambient, dimension, strict, divisors, working, records, births, deadline, away,
                            order_only)
    if found is not _DECLINED:
        return found
    return _maximum_stepwise(variables, ambient, dimension, strict, divisors, working, records, births, deadline, away,
                             order_only=order_only)


_DECLINED = object()


def native_failure(answer, **kinds):
    """The exception that a native composition reports, as the Python steps raise it."""
    from .native_library import Unavailable
    from .polynomial import InputError
    known = dict(GiveUp=GiveUp, NoContact=NoContact, Unavailable=Unavailable, InputError=InputError,
                 ValueError=ValueError, TypeError=TypeError, KeyError=KeyError, **kinds)
    return known.get(answer["raise"], ArithmeticError)(answer["message"])


def _native_maximum(variables, ambient, dimension, strict, divisors, working, records, births, deadline, away,
                    order_only=False):
    """One call of native/centre_maximum.cpp, or _DECLINED for the step-by-step route."""
    from . import native_library
    from .kernel import exprs
    from .kernel_json import kernel_json
    from .native_polynomial import native_ring, row
    from .polynomial import kernel_fraction
    variables = tuple(variables)
    if not native_ring(variables):
        return _DECLINED
    from .algebra_execution import current_execution
    scope = native_library.current_replay_scope()

    def rows(ideal):
        return [row(variables, g) for g in ideal]

    answer = kernel_json(
        "atlas_centre_maximum", "maximum", names=[v.name for v in variables],
        identities=[v._coords[0].identity for v in variables], ambient=rows(ambient), dimension=dimension,
        strict=rows(strict), divisors=[[label, rows(ideal)] for label, ideal in divisors],
        working=[rows(w) for w in working], away=[rows(z) for z in away], births=list(births), order_only=order_only,
        records={label: None if record is None else invariant_row(record) for label, record in records.items()},
        seconds=None if deadline is None else deadline - monotonic(),
        packed_present=current_execution() is None and (scope is None or scope.compute == "cpu"),
        gpu=scope is not None and scope.compute == "gpu")
    if "declined" in answer:
        return _DECLINED
    if "raise" in answer:
        raise native_failure(answer)
    found = answer["maximum"]
    if found is None:
        return None
    value = tuple(INFINITE if entry == "inf" else kernel_fraction(entry) for entry in found["value"])
    return value, tuple(found["key"]), exprs(variables, found["centre"])


def _maximum_stepwise(variables, ambient, dimension, strict, divisors, working, records, births, deadline=None,
                      away=(), order_only=False):
    """The arbitrary-width route of `maximum`: each native operation called in turn."""
    original, chart = tuple(variables), tuple(ambient)
    if not order_only and (deadline is None or monotonic() <= deadline):
        direct = _affine_maximum(original, chart, dimension, strict, divisors, working, records, away)
        if direct is not None:
            if deadline is not None and monotonic() > deadline:
                raise GiveUp("The time allowed for the blowups is over.")
            return direct
    strict = tuple(g for g in strict if not ideal_subset(original, (g,), chart))
    working = [tuple(w) for w in working if not empty_locus(original, (*chart, *strict, *w))]
    if not working or not strict:
        return None
    # Every divisor through the set must be a coordinate hyperplane: one that is
    # not becomes one on the graph of its equation.
    names, graph = {}, {}
    variables, ambient = original, list(chart)
    for label, ideal in divisors:
        if all(empty_locus(original, (*chart, *ideal, *w)) for w in working):
            continue
        g = _principal(original, chart, ideal)
        if g not in original:
            name = chart_expressions(variables).Dummy(f"divisor_{label}")
            variables, graph[name] = (*variables, name), g
            ambient.append(name - g)
            g = name
        names[label] = g
    ctx = _Context(records, births, names.values(), deadline)
    found = []
    covers = cover_products(original, (ideal for ideal in away
        if any(not empty_locus(original, (*chart, *strict, *ideal, *w)) for w in working)))
    pieces, left = [], list(working)
    for unit in dict.fromkeys(covers):
        if unit == 1:
            pieces.append(((), left))
            break
        part = [w for w in left if not radical_subset(original, (unit,), (*chart, *strict, *w))]
        if part:
            pieces.append(((unit,), part))
        left = [w for w in ((*w, unit) for w in left) if not empty_locus(original, (*chart, *strict, *w))]
        if not left:
            break
    frames = [item for units, part in pieces
              for item in _frames(variables, ambient, dimension, tuple(names.values()), part, eliminate=True, units=units)]
    for frame, live, move in frames:
        own = tuple(g for g in map(move, strict) if g != 0)
        live = [tuple(g for g in map(move, w) if g != 0) for w in live]
        # A divisor whose variable has been eliminated does not meet the frame.
        present = tuple((label, v) for label, v in names.items() if v in frame.variables)
        order = jet_order(1, lambda k: any(not frame.empty(*(d for g in own for d in frame.jet(g, k)), *w)
                                         for w in live))
        locus = tuple(d for g in own for d in frame.jet(g, order))
        live = tuple(w for w in live if not frame.empty(*locus, *w))
        coll = tuple(({}, g, Fraction(order)) for g in own)
        state = State(frame, coll, (), present, locus, live, (Fraction(order),), ())
        if order_only:
            # The first entry of the invariant and its locus, as the native route gives them.
            if live:
                found.append(Found((Fraction(order),), (), locus, state))
            continue
        found.extend(_level(state, ctx))
    if not found:
        return None
    indices = maximum_indices((item.value,item.key) for item in found)
    maximum = found[indices[0]]
    centre = None
    for i in indices:
        item = found[i]
        frame = item.state.frame

        def back(gens):
            for swap in reversed(item.state.undo):
                gens = [frame_function(variables, chart_expressions(variables).sympify(g).xreplace(swap)) for g in gens]
            return [g for g in (frame_function(original, chart_expressions(variables).sympify(g).xreplace(graph)) for g in gens) if g != 0]

        # The locus on the open set, then its closure in the chart. `back` is a
        # ring map, so it carries the basis in the frame, where the locus is
        # simplest, to generators of the same image.
        locus = ideal_basis(variables, (*item.centre, *frame.rows, *frame.solved))
        gens = ideal_basis(original, (*chart, *back(locus)))
        for unit in back(frame.units):
            gens = saturate(original, gens, unit)
        gens = ideal_basis(original, gens)
        centre = gens if centre is None or centre == gens else _intersection(original, centre, gens)
    return maximum.value, maximum.key, tuple(centre)
