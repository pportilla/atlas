"""Factor a polynomial over a finite number field using rational norms.

Work in K=Q(theta) and first remove multiplicities by a principal ideal
quotient. In characteristic zero gcd(F, all partials) contains exactly one
fewer copy of each prime of F. Thus (F):(F, partials) is its squarefree part.

A translation x_i -> x_i + theta*a^(i+1) eventually makes its conjugates
pairwise coprime. For a fixed pair of distinct embeddings and monic absolute
factors, equality of the translated factors is polynomial in a. If it held
identically it would hold at zero, and that same nonconstant factor would be
invariant under translations by (theta'-theta'')*(a,a^2,...). Their span is
the full space in characteristic zero. Only finitely many a are exceptional.

Eliminate theta from (m(theta), F_shift). After extension to Qbar the
contracted ideal is generated by the least common multiple of the conjugate
equations; its degree is [K:Q]*deg(F) exactly if they share no factors.
Each rational irreducible factor of that norm then meets F_shift in exactly
one K-irreducible: the Galois group is transitive on the absolute factors
of the rational factor, and the disjoint conjugates distinguish the chosen
embedding of K. Pulling back and taking gcd with F recovers those factors.
All gcds and divisions below are principal ideal quotients in the native
Groebner kernel. SymPy's factorization is an independent comparison.
"""
from functools import cmp_to_key, lru_cache
from itertools import count

from .reference import QQ
from .chart_expressions import chart_expressions
from .native_polynomial import native_ring

from .affine_kernel import (_factor_order, _sparse_expression, frame_derivative, pullbacks,
                            rational_factor_rows, rational_factors, sparse_terms)
from .groebner import CHECK, _MODE, colon, groebner


def _quotient(variables, numerator, denominator, field):
    quotient = colon((numerator,), tuple(denominator), variables, domain=field)
    if quotient is None:
        raise ArithmeticError("The native field ideal quotient is unavailable.")
    return groebner(quotient, variables, order="lex", domain=field).exprs[0]


@lru_cache(maxsize=256)
def factors(poly):
    if poly.domain == QQ:
        return rational_factors(poly)[1]
    from .groebner import _kernel
    if _MODE == "sympy":
        return poly.factor_list()[1]
    if not hasattr(_kernel(), "atlas_coefficient_block_abi"):
        if _MODE == "native":
            raise ArithmeticError("Rebuild the native number-field kernel with make groebner.")
        return poly.factor_list()[1]
    from .field_polynomial import lift, lower, modulus
    variables, field = poly.gens, poly.domain
    degree = poly.total_degree()
    if degree == 0:
        return []
    monic_basis = groebner((poly.as_expr(),), variables, order="lex", domain=field)
    if degree == 1:
        return [(monic_basis.polys[0], 1)]
    theta = chart_expressions(variables).Dummy("factor_field")
    ring = (*variables, theta)
    minimal = modulus(field, theta)
    f = monic_basis.exprs[0]
    lifted = lift(f, variables, field, theta)
    jacobian = [lower(frame_derivative(ring, lifted, {v: 1}), variables, field, theta) for v in variables]
    squarefree = _quotient(variables, f, (f, *jacobian), field)
    squarefree_lift = lift(squarefree, variables, field, theta)
    squarefree_lift, = pullbacks(ring, ring, ring, (squarefree_lift,), minimal)
    extension_degree = field.degree if native_ring(variables) else field.ext.minpoly.degree()
    target_degree = max(sum(m[:-1]) for m,_ in sparse_terms(ring, squarefree_lift)) * extension_degree
    for a in count():
        translations = tuple(theta*a**(i+1) for i in range(len(variables)))
        shift = tuple(v+h for v,h in zip(variables, translations))
        shifted, = pullbacks(ring, (*shift, theta), ring, (squarefree_lift,), minimal)
        basis = groebner((minimal, shifted), (theta, *variables), order="lex")
        norm, = (g for g in basis.exprs if theta not in g.free_symbols)
        if max(sum(m) for m,_ in sparse_terms(variables, norm)) == target_degree:
            break
    reverse = tuple(v-h for v,h in zip(variables, translations))
    answer = []
    for row, _, _ in rational_factor_rows(variables, norm)[1]:
        image, = pullbacks(ring, reverse, variables, (_sparse_expression(variables, row),), minimal)
        divisor = lower(image, variables, field, theta)
        cofactor = _quotient(variables, squarefree, (divisor,), field)
        prime = _quotient(variables, squarefree, (cofactor,), field)
        # A principal lex basis is already the normalized factor, including
        # its power-basis coefficient rows for the public Poly adapter.
        prime_ideal = groebner((prime,), variables, order="lex", domain=field)
        power, remaining = 0, f
        while prime_ideal.contains(remaining):
            remaining = _quotient(variables, remaining, (prime,), field)
            power += 1
        answer.append((prime_ideal.polys[0], power))
    if len(answer) > 1:
        # Field coefficients compare by their descending power-basis lists.
        # Their sorted ranks preserve these comparisons, with rank 0 for
        # the empty list (zero). Compare sparse polynomials in those ranks.
        if native_ring(variables):
            from .candidate_field import field_power_rows
            supports = [field_power_rows(p) for p,_ in answer]
        else:
            supports = [{e: tuple(c.to_list()) for e,c in p.rep.to_dict().items()} for p,_ in answer]
        ranks = {c: i for i,c in enumerate(sorted({c for s in supports for c in s.values()}), 1)}
        order = cmp_to_key(lambda a,b: _factor_order(a, b, len(variables)))
        keys = [(max(e[0] for e in s), power, order({e: ranks[c] for e,c in s.items()}))
                for s,(_,power) in zip(supports, answer)]
        answer = [answer[i] for i in sorted(range(len(answer)), key=keys.__getitem__)]
    if CHECK:
        expected = poly.factor_list()[1]
        if expected != answer:
            raise AssertionError("The norm factorization over the number field differs from SymPy's.")
    return answer


def compose(variables, mapping, base, functions, field):
    """Substitute polynomials over K in the common presentation Q[theta]/m."""
    if field == QQ:
        return pullbacks(variables, mapping, base, functions)
    from .field_polynomial import lift, lower, modulus
    theta = chart_expressions(variables).Dummy("field_map")
    equations = tuple(lift(f, base, field, theta) for f in functions)
    images = tuple(lift(f, variables, field, theta) for f in mapping)
    values = pullbacks((*variables, theta), (*images, theta), (*base, theta), equations, modulus(field, theta))
    return tuple(lower(f, variables, field, theta) for f in values)


def linear(variables, expression, x, field):
    """The two coefficients of a polynomial of degree one in x."""
    from .affine_kernel import frame_linear
    if field == QQ:
        return frame_linear(variables, expression, x)
    from .field_polynomial import lift, lower
    theta = chart_expressions(variables).Dummy("field_linear")
    pair = frame_linear((*variables, theta), lift(expression, variables, field, theta), x)
    return None if pair is None else tuple(lower(f, variables, field, theta) for f in pair)
