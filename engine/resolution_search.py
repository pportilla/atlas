from __future__ import annotations
"""Candidates, not certificates of success, for an exact resolution verifier.

The early candidates make common smooth centers inexpensive to find. Integer
codes additionally cover arbitrary finite lists of rational center generators,
number-field boundary ideals and all polynomial degrees. Each candidate and
each time allowance reappears under the dovetail schedule. Search has no
useful general complexity bound; callers should run attempts in killable
workers and retain the distinction between rejection, timeout and success.
"""
from dataclasses import dataclass
from itertools import chain, combinations, count, islice

from . import native_polynomial as np
from .chart_expressions import chart_expressions
from .reference import sp
from .reference import QQ
from .kernel_json import kernel_json
from .polynomial import integer_from_decimal, sparse_row

from .affine_kernel import (_polynomial, _request, _ring, _sparse_expression,
                            rational_factor_rows)
from .blowup_ideal import ideal_basis


@dataclass(frozen=True)
class ResolutionCandidate:
    center: tuple
    projective: tuple
    boundary: tuple
    domain: object
    primitive: sp.Expr | None
    source: str


def _projective(variables, length):
    existing = {v.name for v in variables}
    result = []
    for i in range(length):
        name = f"U{i+1}"
        while name in existing:
            name += "_"
        existing.add(name)
        result.append(chart_expressions(variables).Symbol(name))
    return tuple(result)


def _candidate(variables, center, source):
    center = tuple(center)
    # The pullback of J is invertible. On chart i it is generated by f_i,
    # since f_j=f_i*(U_j/U_i). Its support is the whole exceptional locus
    # if this candidate has one divisor; the verifier checks this assertion.
    return ResolutionCandidate(center, _projective(variables, len(center)),
                               () if center == (1,) else (center,), QQ, None, source)


def _support_profile(variables, f):
    ring = _ring(variables)

    def native():
        row, = _request(["support_profile", ring.header, ring.text(f)])
        degree, count, *active = row.split()
        return integer_from_decimal(degree), int(count), tuple(map(int, active))


    return native()


def _singular_coordinate_subspaces(variables, f):
    ring = _ring(variables)
    subspaces = chain.from_iterable(combinations(range(len(variables)), size)
                                    for size in range(2, len(variables)))
    # Bounded batches keep discovery lazy even in a large ambient space.
    while subset_batch := tuple(islice(subspaces, 128)):
        def native():
            rows = _request(["singular_subspaces", ring.header, ring.text(f),
                             *(" ".join(map(str, indices)) for indices in subset_batch)])
            return tuple(map(int, rows))


        for j in native():
            yield tuple(variables[i] for i in subset_batch[j])


def _candidate_row(variables, value):
    if np.native_ring(variables):
        return np.row(variables, value)
    ring = _ring(variables)
    row, = _request(["function", ring.header, ring.text(value)])
    return row


def _jacobian_support(variables, f):
    """Serialize the generators of the geometric Jacobian locus in caller order."""
    def native():
        rows = kernel_json("atlas_resolution_candidate", "jacobian_support", width=len(variables),
                           row=_candidate_row(variables, f))
        values = [_sparse_expression(variables, row) for row in rows]
        return tuple(sorted(values, key=chart_expressions(variables).default_sort_key))

    return native()


def _two_blowup_candidates(variables, f):
    """Read the native composite centres and their two projective boundary ideals."""
    expr = f.as_expr() if hasattr(f, "as_expr") else f
    projective = _projective(variables, 3)
    row = None
    for i, j in combinations(range(len(variables)), 2):
        def native():
            nonlocal row
            if row is None:
                row = _candidate_row(variables, expr)
            proposals = kernel_json("atlas_resolution_candidate", "two_blowups", width=len(variables),
                                    row=row, first=i, second=j)
            results = []
            for data in proposals:
                parameters = tuple(_sparse_expression(variables, r) for r in data["parameters"])
                if np.native_ring(variables):
                    centre = tuple(_sparse_expression(variables, r) for r in data["centre"])
                else:
                    # Preserve the original factored display on external symbolic objects.
                    centre = tuple(sp.Mul(*(parameters[k] for k in factors)) for factors in data["factors"])
                symbols = (*parameters, *projective)
                boundary = tuple(tuple(symbols[k] for k in ideal) for ideal in data["boundary"])
                results.append(ResolutionCandidate(centre, projective, boundary, QQ, None,
                                                   "two blowups along a repeated rational tangent"))
            return tuple(results)

        yield from native()


def priority_candidates(variables, polynomial):
    """Finite sequence of inexpensive geometric hypotheses in the caller’s coordinates."""
    variables = tuple(variables)
    api = chart_expressions(variables)
    f = polynomial.as_expr() if hasattr(polynomial, "as_expr") else api.sympify(polynomial)
    yield _candidate(variables, (api.S.One,), "identity")
    # Do not compute a large singular ideal before offering the origin.
    yield _candidate(variables, variables, "origin")
    seen = {frozenset((api.S.One,)), frozenset(variables)}

    def new(generators):
        key = frozenset(generators)
        if not key or key in seen:
            return False
        seen.add(key)
        return True

    degree, term_count, used = _support_profile(variables, f)
    active = tuple(variables[i] for i in used)
    if len(active) >= 2 and new(active):
        yield _candidate(variables, active, "support coordinate subspace")

    for center in _singular_coordinate_subspaces(variables, f):
        if new(center):
            yield _candidate(variables, center, "singular coordinate subspace")

    # These limits only govern the early shortcuts, never the exhaustive family.
    if len(variables) <= 5 and degree <= 14 and term_count <= 140:
        center = _jacobian_support(variables, f)
        if new(center):
            yield _candidate(variables, center, "equations for the geometric Jacobian locus")
        if 2 <= len(center) <= 8 and degree <= 6 and len(variables) <= 3:
            simplified = ideal_basis(variables, center)
            if new(simplified):
                yield _candidate(variables, simplified, "simplified Jacobian center")
        factors = [_sparse_expression(variables, row) for row, _, _ in rational_factor_rows(variables, f)[1]]
        for a, b in combinations(factors, 2):
            if new((a,b)):
                yield _candidate(variables, (a,b), "intersection of two rational factors")
        yield from _two_blowup_candidates(variables, f)


def decode_candidate(variables, code):
    """Decode a finite certificate description; malformed codes return None.

    Field: d-1 followed, for d>1, by the d signed coefficients of a monic
    irreducible integral polynomial and the root index. Then a nonempty
    center and a list of boundary ideals (each nonempty). Nonempty lengths
    are stored minus one. Each polynomial is a nonempty list of terms:
    signed nonzero integer coefficient, optional field-basis index, and one
    nonnegative exponent per variable. All natural numbers use Elias gamma
    on n+1; signed integers use 0,+1,-1,+2,-2,... . Each boundary generator
    must be homogeneous in U. Remove the binary sentinel 1 from code+1.

    Clearing rational denominators does not change any ideal. Every number
    field admits an integral primitive element with monic minimal polynomial.
    Hence the format covers any finite description of this prescribed kind.
    """
    if not isinstance(code, int) or code < 0:
        raise ValueError("Candidate code must be a nonnegative integer.")
    candidate, _ = _decode_range(variables, code)
    return candidate


def _decode_range(variables, code):
    variables = tuple(variables)
    def native():
        answer = kernel_json("atlas_resolution_candidate", "decode", width=len(variables), code=format(code,"x"))
        next_code = int(answer["next"],16)
        if "candidate" not in answer:
            return None, next_code
        data = answer["candidate"]
        domain, primitive = QQ, None
        if "coefficients" in data:
            coefficients = tuple(map(integer_from_decimal,data["coefficients"]))
            if np.native_ring(variables):
                from .candidate_field import indexed_field
                domain, primitive = indexed_field(coefficients,data["index"])
            else:
                from .field_coefficient import indexed_field
                domain, primitive = indexed_field(coefficients,sp.Symbol("T"),data["index"])
        center = tuple(_polynomial(sparse_row(row), variables) for row in data["center"])
        projective = _projective(variables,len(center))
        axes = (*variables,*projective) if primitive is None else (*variables,*projective,primitive)
        boundary = tuple(tuple(_polynomial(sparse_row(row), axes) for row in ideal) for ideal in data["boundary"])
        return ResolutionCandidate(center,projective,boundary,domain,primitive,f"integer code {code:#x}"), next_code
    return native()


def _first_code(variables):
    return int(kernel_json("atlas_resolution_candidate", "first", width=len(variables)),16)


def _code_trials(variables, first, stop=None):
    while stop is None or first < stop:
        candidate, first = _decode_range(variables, first)
        yield candidate, first


def candidates(variables, polynomial):
    """Yield the priority guesses, then all well-formed integer-code candidates."""
    variables = tuple(variables)
    yield from priority_candidates(variables, polynomial)
    for candidate, _ in _code_trials(variables, _first_code(variables)):
        if candidate is not None:
            yield candidate


def scheduled_candidates(variables, polynomial, *, initial_seconds=1):
    """Yield (candidate, finite attempt budget in seconds) with unbounded revisits.

    Each pass revisits the finite range already discovered at its start,
    increasing the verification allowance. Each retry (including an invalid
    prefix) is interleaved with a discovery step. No table of all prior codes
    is retained. Callers may skip definite rejections.
    """
    if not isinstance(initial_seconds, int) or initial_seconds < 1:
        raise ValueError("initial_seconds must be a positive integer.")
    variables = tuple(variables)
    early = []
    for candidate in priority_candidates(variables, polynomial):
        early.append(candidate)
        yield candidate, initial_seconds
    first = _first_code(variables)
    frontier = first
    discovery = _code_trials(variables, first)
    for effort in count(2):
        # Capture the frontier before advancing the discovery iterator.
        revisited = _code_trials(variables, first, frontier)
        for retry in chain(early, (candidate for candidate, _ in revisited)):
            candidate, frontier = next(discovery)
            if candidate is not None:
                yield candidate, initial_seconds
            if retry is not None:
                yield retry, initial_seconds * effort
