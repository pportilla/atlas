"""Rational quotient algebras globally and at the coordinate origin.

The local order takes the terms of lowest total degree first, breaking ties
by the requested order on the coordinates. A homogeneous lift realizes this
order with an ordinary global Gröbner computation (Lazard homogenization).
The standard monomials give homogeneous bases of the successive pieces of
the maximal-ideal filtration. In finite length these lift to a basis of the
local algebra. A surviving pure power in every degree implies infinite length.
"""

from . import native_polynomial as np
from .algebra_execution import cpu_stage, stage_label
from .algebra_groebner import reduced_basis
from .polynomial import InputError, format_poly
from .quotient_monomials import quotient_monomials


def _leading(powers, order):
    if order == "lex":
        return max(powers)
    return max(powers, key=lambda e: (sum(e), tuple(-i for i in reversed(e))))


def _homogeneous_local_basis(variables, rows, order):
    # In a homogeneous row t^(d-|a|)*x^a, the largest t exponent selects
    # the smallest x degree. The block order breaks ties in the x variables.
    extended = (np.Dummy("homogenizer"), *variables)
    with cpu_stage("homogenize_local_generators", generators=len(rows)):
        lifted = []
        for row in rows:
            degree = max(map(sum, row))
            lifted.append(np.from_terms(extended, {(degree - sum(e), *e): c for e, c in row.items()}))
    with stage_label("local_standard_basis"):
        return reduced_basis(lifted, extended, order="lex" if order == "lex" else "first")


def _initial_monomials(variables, generators, order, local):
    """Generate the global or local initial ideal in the original coordinates."""
    with cpu_stage("inspect_quotient_generators", generators=len(generators)):
        rows = [np.terms(variables, f) for f in generators if f]
        origin = (0,) * len(variables)
        if any(origin in row and (local or len(row) == 1) for row in rows):
            return [origin]
        if all(len(row) == 1 for row in rows):
            return [next(iter(row)) for row in rows]
        if len(rows) == 1:
            # Leading monomials multiply, so the head of a principal generator
            # generates the initial ideal even after localization at the origin.
            powers = rows[0].keys()
            if local:
                degree = min(map(sum, powers))
                powers = [e for e in powers if sum(e) == degree]
            return [_leading(powers, order)]
        # An ideal generated by homogeneous forms already equals its tangent
        # cone. In particular this also works for positive-dimensional cones.
        lift = local and any(len({sum(e) for e in row}) > 1 for row in rows)

    if not lift:
        with stage_label("quotient_basis"):
            basis = reduced_basis(generators, variables, order=order)
        with cpu_stage("quotient_initial_monomials", generators=len(basis.exprs)):
            return [_leading(np.terms(variables, f), order) for f in basis.exprs]

    basis = _homogeneous_local_basis(variables, rows, order)
    # For f=sum(a_i*f_i), homogenizing the equality to a common degree gives
    # t^k*f^h in (f_i^h). A leading monomial of this homogeneous basis
    # therefore divides LM(t^k*f^h); deleting its t exponent gives a divisor
    # of the local LM(f). Conversely every basis row dehomogenizes into I.
    # Denominators that are units at the origin have constant local head.
    with cpu_stage("local_initial_monomials", generators=len(basis.exprs)):
        heads = []
        for f in basis.exprs:
            terms = np.terms(basis.gens, f)
            top = max(e[0] for e in terms)
            heads.append(_leading((e[1:] for e in terms if e[0] == top), order))
        return heads


def _jacobian(variables, terms):
    with cpu_stage("jacobian_generators", variables=len(variables), terms=len(terms)):
        partials = [{} for _ in variables]
        for powers, coefficient in terms.items():
            for i, power in enumerate(powers):
                if power:
                    exponent = powers[:i] + (power - 1,) + powers[i + 1:]
                    partials[i][exponent] = power * coefficient
        return tuple(np.from_terms(variables, partial) for partial in partials)


def handle(operation, ring, operands):
    """Compute validated QQ quotients, local Jacobian algebras and their lengths."""
    if ring["field"] != "QQ" or ring["order"] not in ("lex", "grevlex"):
        raise InputError("Quotient algebras require QQ and lex or grevlex order.")
    variables = tuple(map(np.Symbol, ring["variables"]))
    local = operation != "quotient-basis"
    number = operation in ("milnor-number", "tjurina-number")
    result = {"ring": ring, "scope": "origin" if local else "global"}
    if operation in ("quotient-basis", "local-quotient-basis"):
        generators = operands["ideal"]
        result["type"] = "quotient-basis"
    elif number or operation == "local-jacobian-algebra":
        f = operands["polynomial"]
        with cpu_stage("hypersurface_first_order" if number else "hypersurface_at_origin",
                       variables=len(variables)):
            if not variables:
                raise InputError("A hypersurface germ requires at least one coordinate.")
            terms = np.terms(variables, f)
            if (0,) * len(variables) in terms:
                raise InputError("The hypersurface must pass through the origin.")
            # A linear term makes its partial derivative a unit at the origin.
            # Both local quotients then have length zero.
            if number and any(sum(powers) == 1 for powers in terms):
                return {**result, "type": "integer", "finite": True, "value": 0}
        generators = _jacobian(variables, terms)
        if operation == "tjurina-number":
            generators = (*generators, f)
        result["type"] = "integer" if number else operation
        if not number:
            result["generators"] = [format_poly(np.terms(variables, g), ring["variables"]) for g in generators]
    else:
        raise InputError(f"Unknown quotient algebra operation {operation!r}.")

    heads = _initial_monomials(variables, generators, ring["order"], local)
    with cpu_stage("quotient_length" if number else "standard_monomials", generators=len(heads)):
        dimension, basis = quotient_monomials(len(variables), heads, include_basis=not number)
        result["finite"] = dimension is not None
        if number:
            result["value"] = dimension
        else:
            result["dimension"] = dimension
            result["basis"] = (None if basis is None else
                               [format_poly({e: 1}, ring["variables"]) for e in basis])
    return result
