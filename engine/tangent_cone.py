"""The scheme-theoretic tangent cone and Hilbert series of a rational local ideal."""

from . import native_polynomial as np
from .algebra_execution import cpu_stage
from .hilbert_samuel import _invariants, monomial_hilbert_series
from .point_geometry import decode_terms, encode_terms, request
from .local_standard import _standard_basis
from .point_germs import _large_translation, centered_ideal
from .polynomial import InputError, format_poly, integer_from_decimal
from .rational_point import coordinate_fraction, normalize_point


def _initial_forms(variables, shifts, generators, order, include_forms):
    """Return the leading powers and, on request, every term at their degree."""
    if any(shifts):
        with cpu_stage("center_at_point", variables=len(variables), generators=len(generators)):
            if len(generators) == 1 and _large_translation(variables, shifts, generators[0]):
                f, = generators
                if not include_forms:
                    # For a hypersurface, the Hilbert series depends only on
                    # the order of its equation. No directional coefficients
                    # need to be computed when only the series is requested.
                    from .point_order import order_at_rational_point
                    degree = order_at_rational_point(variables, shifts, f)
                    return [(degree,) + (0,)*(len(variables)-1)], []
                from .point_initial_form import principal_initial_form
                generators = (principal_initial_form(variables, shifts, f),)
            else:
                generators = centered_ideal(variables, shifts, generators)

    # The associated graded ideal is generated by the initial forms of a
    # local standard basis. Its homogeneous leading monomials, in the chosen
    # global tie order, are exactly the local heads of that same basis.
    basis = _standard_basis(variables, generators, order)
    with cpu_stage("tangent_cone_initial_forms", generators=len(basis)):
        result = request("cone_forms", point=["0"] * len(variables), order=order, forms=include_forms,
                         ideal=[encode_terms(np.terms(variables, f)) for f in basis])
    heads = [tuple(map(integer_from_decimal, e)) for e in result["heads"]]
    return heads, [decode_terms(form) for form in result["forms"]]


def handle(operation, ring, operands):
    if operation not in ("tangent-cone", "tangent-cone-hilbert-series"):
        raise InputError(f"Unknown tangent cone operation {operation!r}.")
    if ring["field"] != "QQ" or ring["order"] not in ("lex", "grevlex"):
        raise InputError("Tangent cones require QQ and lex or grevlex order.")
    names = ring["variables"]
    variables = tuple(map(np.Symbol, names))
    width = len(variables)
    result = {"type": operation, "ring": ring, "scope": "origin"}
    shifts = (0,)*width
    if "point" in operands:
        point = normalize_point(operands["point"], width)
        shifts = tuple(map(coordinate_fraction, point))
        result.update(scope="point", point=point)

    generators = tuple(np.coerce(f) for f in operands["ideal"] if f)
    cone = operation == "tangent-cone"
    heads, forms = _initial_forms(variables, shifts, generators, ring["order"], cone)
    with cpu_stage("tangent_cone_staircase", generators=len(heads)):
        if cone:
            dimension, multiplicity, _ = _invariants(width, heads, [])
            result.update(dimension=dimension, multiplicity=multiplicity, coordinate_system="tangent",
                          generators=[format_poly(row, names) for row in forms])
        else:
            result.update(monomial_hilbert_series(width, heads))
    return result
