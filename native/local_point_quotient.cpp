Basis partial_derivatives(const Polynomial& f, size_t width) {
    Basis partials(width);
    for (const auto& [e,c] : f) {
        for (size_t i=0; i<width; ++i) if (e[i] != 0) {
            auto powers = e;
            --powers[i];
            partials[i].emplace(std::move(powers),c*e[i]);
        }
    }
    return partials;
}

namespace {
bool at_origin(const PointRow& point) {
    return std::all_of(point.begin(),point.end(),[](const auto& p) { return p == 0; });
}

std::optional<Polynomial> sparse_square_root(const Polynomial& f, bool free_constant = false) {
    // Recover the possible monic square root from largest terms downwards.
    // If the missing part starts with d, the discrepancy starts with
    // 2*lead(root)*d. The first incompatible term disproves the square.
    // The budget bounds only this optional certificate, since a sparse
    // polynomial can have a denser square root.
    const auto& [top,scalar] = *f.rbegin();
    Powers lead(top.size());
    for (size_t i=0; i<top.size(); ++i) {
        if (mpz_odd_p(top[i].get_mpz_t())) return std::nullopt;
        lead[i] = top[i]/2;
    }
    auto pending = f;
    pending.erase(top);
    for (auto& t : pending) t.second /= scalar;
    Polynomial root{{lead,1}};
    const size_t budget = 4*f.size()+8;
    auto subtract = [&](Powers e, const mpq_class& c) {
        auto it = pending.try_emplace(std::move(e),0).first;
        it->second -= c;
        if (it->second == 0) pending.erase(it);
    };
    while (!pending.empty()) {
        // Reconstructing a primitive from its gradient leaves its constant
        // unspecified. A lone constant discrepancy is immaterial then.
        if (free_constant && pending.size() == 1 && pending.begin()->first == Powers(top.size())) break;
        if (root.size() >= budget || pending.size() > 4*budget) return std::nullopt;
        const auto& [e,c] = *pending.rbegin();
        Powers next(e.size());
        for (size_t i=0; i<e.size(); ++i) {
            if (e[i] < lead[i]) return std::nullopt;
            next[i] = e[i]-lead[i];
        }
        if (next >= root.begin()->first) return std::nullopt;
        const mpq_class coefficient = c/2;
        for (const auto& [a,b] : root) {
            Powers key = next;
            for (size_t i=0; i<key.size(); ++i) key[i] += a[i];
            subtract(std::move(key),2*b*coefficient);
        }
        Powers square = next;
        for (auto& k : square) k *= 2;
        subtract(std::move(square),coefficient*coefficient);
        root.emplace(std::move(next),coefficient);
    }
    return root;
}

bool repeated_gradient(const Basis& rows, const PointRow& point) {
    if (rows.size() != point.size() || point.size() <= 1) return false;
    Polynomial primitive;
    for (size_t i=0; i<rows.size(); ++i) {
        for (const auto& [e,c] : rows[i]) {
            auto powers = e;
            ++powers[i];
            const mpq_class coefficient = c/powers[i];
            auto [it,fresh] = primitive.emplace(std::move(powers),coefficient);
            if (!fresh && it->second != coefficient) return false;
        }
    }
    if (primitive.empty() || partial_derivatives(primitive,point.size()) != rows) return false;
    // If the primitive is a square up to a scalar and additive constant,
    // every supplied derivative vanishes on its square root. Verify the
    // entire factor passes through the requested point.
    auto root = sparse_square_root(primitive,true);
    return root && !nonzero_at_point(*root,point);
}

// For f=c+sum f_i(x_i), the Jacobian ideal is generated by univariate
// derivatives. In the local DVR, f_i-f_i(p_i) has order one more than
// f_i'. Since f(p)=0 their sum adds no Tjurina relation. A missing
// coordinate leaves a free variable in the quotient.
std::optional<PointQuotient> separated_hypersurface(const Polynomial& f,
        const PointRow& point, bool listing) {
    const size_t width = point.size();
    std::vector<Polynomial> univariate(width);
    for (const auto& [e,c] : f) {
        auto axis = std::find_if(e.begin(),e.end(),[](const auto& a) { return a != 0; });
        if (axis == e.end()) continue;
        if (std::any_of(axis+1,e.end(),[](const auto& a) { return a != 0; })) return std::nullopt;
        univariate[axis-e.begin()].emplace(Powers{*axis-1},c * *axis);
    }
    std::vector<Powers> heads;
    for (size_t i=0; i<width; ++i) {
        if (univariate[i].empty()) return PointQuotient{};
        Powers h(width);
        h[i] = point[i] == 0 ? univariate[i].begin()->first.front()
                             : order_at_point(univariate[i],{point[i]});
        heads.push_back(std::move(h));
    }
    return monomial_point_quotient(width,heads,listing);
}

PointQuotient from_ideal(const Basis& ideal, const std::vector<std::string>& names,
                        const PointRow& point, bool lex, bool prefer_modular, bool listing) {
    const size_t width = names.size();
    const bool origin = at_origin(point);
    const Powers zero(width);
    // The simplification acts in the local ring. For example a monomial
    // in moving axes is a unit, and a full-rank Jacobian generates m_p.
    Basis rows;
    if (origin) {
        for (const auto& f : ideal) if (!f.empty()) {
            if (f.count(zero)) return {0,{},{}};
            rows.push_back(f);
        }
    } else {
        rows = simplify_point_generators(ideal,point);
        if (rows.size() == 1 && rows.front().size() == 1 && rows.front().count(zero)) return {0,{},{}};
    }
    // The height theorem precludes finite colength for fewer than n
    // generators of a proper ideal in the regular local ring of dimension n.
    if (rows.size() < width) return {};
    if (std::all_of(rows.begin(),rows.end(),[](const auto& row) { return row.size()==1; })) {
        std::vector<Powers> heads;
        for (const auto& f : rows) heads.push_back(f.begin()->first);
        return monomial_point_quotient(width,heads,listing);
    }
    if (width == 1) {
        std::optional<mpz_class> least;
        for (const auto& f : rows) {
            const auto order = origin ? f.begin()->first.front() : order_at_point(f,point);
            if (!least || order < *least) least = order;
        }
        return monomial_point_quotient(width,{Powers{*least}},listing);
    }
    bool sparse = !origin && use_sparse_point_basis(rows,point);
    if (sparse) {
        // A diagonal étale power substitution rescales every tangent
        // coordinate by a nonzero scalar. It preserves the initial
        // exponents, so the staircase itself needs no back-substitution.
        if (auto chart = point_power_coordinates(rows,point))
            return from_ideal(chart->generators,names,chart->point,lex,prefer_modular,listing);
        if (auto heads = regular_point_heads(rows,names,point,lex,prefer_modular))
            return monomial_point_quotient(width,*heads,listing);
    }
    if (!sparse && !origin) rows = translate_unbounded(rows,point);
    const auto basis = sparse ? standard_basis_at_point(rows,names,point,lex,prefer_modular)
                              : standard_basis(rows,names,lex,prefer_modular);
    std::vector<Powers> heads;
    heads.reserve(basis.size());
    for (const auto& f : basis) if (!f.empty())
        heads.push_back(sparse ? head_at_point(f,point,lex) : local_head(f,lex));
    return monomial_point_quotient(width,heads,listing);
}
}

std::optional<mpz_class> ideal_colength_at_origin(const Basis& generators, const std::vector<std::string>& names) {
    return from_ideal(generators, names, PointRow(names.size()), false, false, false).dimension;
}

PointQuotient quotient_at_point(const std::string& operation, const Basis& inputs,
        const std::vector<std::string>& names, const PointRow& point, bool lex, bool prefer_modular) {
    const size_t width = names.size();
    if (point.size()!=width) throw std::invalid_argument("Incorrect local point dimension.");
    if (operation=="local-quotient-basis") {
        if (use_sparse_point_basis(inputs,point) && repeated_gradient(inputs,point)) return {};
        return from_ideal(inputs,names,point,lex,prefer_modular,true);
    }
    const bool jacobian = operation=="local-jacobian-algebra";
    const bool tjurina = operation=="tjurina-number";
    if (!jacobian && !tjurina && operation!="milnor-number")
        throw std::invalid_argument("Unknown local quotient operation.");
    if (!width) throw std::invalid_argument("A hypersurface germ requires at least one coordinate.");
    if (inputs.size()!=1) throw std::invalid_argument("A hypersurface germ requires exactly one polynomial.");
    const auto& f = inputs.front();
    const auto order = hypersurface_jet_order(f,point);
    if (order == 0) throw HypersurfaceOutside(at_origin(point));
    if (order == 1) return {0,{},jacobian ? partial_derivatives(f,width) : Basis{}};
    if (f.empty()) return {std::nullopt,{},jacobian ? Basis(width) : Basis{}};
    if (width > 1) {
        if (auto separated = separated_hypersurface(f,point,jacobian)) {
            if (jacobian) separated->derivatives = partial_derivatives(f,width);
            return std::move(*separated);
        }
    }
    if (width > 1 && use_sparse_point_basis({f},point) && sparse_square_root(f)) {
        // For f=c*g² on the hypersurface, g(p)=0 and the Tjurina and
        // Jacobian ideals are contained in (g). The hypersurface g=0 has
        // positive local dimension, so both quotients have infinite length.
        return {std::nullopt,{},jacobian ? partial_derivatives(f,width) : Basis{}};
    }
    if (!jacobian && width == 1) {
        // In the DVR, f=u*t^k and df/dt has order k-1 in characteristic
        // zero. The additional Tjurina generator leaves this length intact.
        return {order_at_point(f,point)-1,{},{}};
    }
    auto generators = partial_derivatives(f,width);
    if (tjurina) generators.push_back(f);
    auto result = from_ideal(generators,names,point,lex,prefer_modular,jacobian);
    if (jacobian) result.derivatives = std::move(generators);
    return result;
}
