#include "local_quotient_initial.hpp"
#include <algorithm>

namespace atlas::local {
std::optional<std::vector<Powers>> regular_point_heads(const Basis& ideal,
        const std::vector<std::string>& names, const PointRow& point, bool lex, bool prefer_modular) {
    if (names.empty() || ideal.size() != names.size()) return std::nullopt;
    Basis forms;
    for (const auto& row : ideal) {
        if (row.empty()) return std::nullopt;
        auto initial = bounded_initial_at_point(row, point);
        if (!initial) return std::nullopt;
        forms.push_back(std::move(*initial));
    }

    // A finite-colength ideal generated by n homogeneous positive-order
    // elements of QQ[u_1,...,u_n] is a homogeneous regular sequence.
    // Consequently its associated graded ideal is generated by these
    // initial forms as well (induct on the nonzerodivisor at each step).
    // A pure-power leading monomial in each variable proves finite colength.
    auto basis = standard_basis(forms, names, lex, prefer_modular);
    std::vector<bool> bounded(names.size());
    std::vector<Powers> heads;
    for (const auto& row : basis) {
        auto h = local_head(row, lex);
        auto axis = std::find_if(h.begin(), h.end(), [](const auto& e) { return e != 0; });
        if (axis == h.end()) return std::nullopt;
        if (std::none_of(axis + 1, h.end(), [](const auto& e) { return e != 0; }))
            bounded[axis - h.begin()] = true;
        heads.push_back(std::move(h));
    }
    if (std::find(bounded.begin(), bounded.end(), false) != bounded.end()) return std::nullopt;
    return heads;
}
}
