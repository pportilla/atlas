Basis monomial_contraction(const Basis& rows, const Basis& prime, size_t n) {
    // A coordinate outside P becomes a unit. Among the remaining variables,
    // every associated prime of the projected monomial ideal is contained in P.
    std::vector<bool> retained(n);
    for (size_t i = 0; i < n; ++i) {
        Powers e(n);
        e[i] = 1;
        retained[i] = member_lex({{e,1}},prime);
    }
    std::vector<Powers> minimal;
    for (const auto& f : rows) {
        auto e = f.begin()->first;
        for (size_t i = 0; i < n; ++i) if (!retained[i]) e[i] = 0;
        if (std::any_of(minimal.begin(),minimal.end(),[&](const auto& g) { return local::monomial_divides(g,e); })) continue;
        minimal.erase(std::remove_if(minimal.begin(),minimal.end(),[&](const auto& g) { return local::monomial_divides(e,g); }),minimal.end());
        minimal.push_back(std::move(e));
    }
    std::sort(minimal.begin(),minimal.end(),std::greater<>());
    Basis result;
    for (auto& e : minimal) result.push_back({{std::move(e),1}});
    return result;
}

// At (p) every nonzero ideal is generated by a power of p. Compute the
// valuation of the gcd in a single FLINT context, without factoring inputs.
Polynomial height_one(const Basis& rows, const Polynomial& p, size_t n) {
    if (p.size() == 1) {
        // A monomial prime generator is a coordinate.
        const auto& e = p.begin()->first;
        const auto axis = std::find(e.begin(),e.end(),1) - e.begin();
        mpz_class valuation = rows.front().begin()->first[axis];
        for (const auto& f : rows) for (const auto& term : f)
            valuation = std::min(valuation,term.first[axis]);
        Powers powers(n);
        powers[axis] = valuation;
        return {{std::move(powers),1}};
    }
    // At wide exponents exact division can expand a lacunary quotient.
    // The squarefree p divides neither x_j nor its nonzero partial
    // derivative, so D=x_j*d/dx_j lowers a positive valuation by one.
    // Choose an axis with varying exponents to ensure Dp is nonzero mod p.
    if (std::any_of(rows.begin(),rows.end(),[](const auto& f) {
        return std::any_of(f.begin(),f.end(),[](const auto& term) {
            return std::any_of(term.first.begin(),term.first.end(),[](const auto& e) { return e > 64; });
        });
    })) {
        const auto& a = p.begin()->first;
        const auto& b = p.rbegin()->first;
        const auto axis = std::mismatch(a.begin(),a.end(),b.begin()).first - a.begin();
        const Basis prime{p};
        std::optional<size_t> valuation;
        for (auto derivative : rows) {
            size_t k = 0;
            while ((!valuation || k < *valuation) && member_lex(derivative,prime)) {
                ++k;
                for (auto term = derivative.begin(); term != derivative.end();) {
                    if (term->first[axis] == 0) term = derivative.erase(term);
                    else { term->second *= term->first[axis]; ++term; }
                }
            }
            valuation = k;
            if (!k) break;
        }
        return primary::power(p,*valuation,n);
    }
    local::SparseLexRing ring(n);
    PolyValue common(ring.ctx), divisor(ring.ctx), residual(ring.ctx), quotient(ring.ctx);
    ring.write(common.p,rows.front());
    ring.write(divisor.p,p);
    for (size_t i = 1; i < rows.size(); ++i) {
        ring.write(residual.p,rows[i]);
        if (!fmpq_mpoly_gcd(quotient.p,common.p,residual.p,ring.ctx))
            throw std::runtime_error("Failed to compute polynomial gcd for prime localization.");
        fmpq_mpoly_swap(common.p,quotient.p,ring.ctx);
        if (fmpq_mpoly_is_fmpq(common.p,ring.ctx)) return {{Powers(n),1}};
    }
    if (fmpq_mpoly_equal(common.p,divisor.p,ring.ctx)) return p;
    fmpq_mpoly_set(residual.p,common.p,ring.ctx);
    while (fmpq_mpoly_divides(quotient.p,residual.p,divisor.p,ring.ctx))
        fmpq_mpoly_swap(residual.p,quotient.p,ring.ctx);
    if (!fmpq_mpoly_divides(quotient.p,common.p,residual.p,ring.ctx))
        throw std::logic_error("Inexact division reconstructing a prime power.");
    return ring.read(quotient.p);
}

Polynomial nonunit_part(const Polynomial& f, const Basis& prime, size_t n, bool* linear_factors = nullptr) {
    // In the UFD QQ[x], a principal ideal contracts to the product of those
    // irreducible powers whose primes lie under P. Apply the same cancellation
    // to each generator before computing a general localized ideal.
    Polynomial product{{Powers(n),1}};
    for (const auto& [factor, exponent] : primary::factors(f,n)) {
        if (member_lex(factor,prime)) {
            if (linear_factors && *linear_factors) {
                for (const auto& [e,c] : factor) {
                    if (local::total_degree(e) > 1) { *linear_factors = false; break; }
                }
            }
            auto p = exponent == 1 ? factor : primary::power(factor,exponent,n);
            product = primary::multiply(product,p);
        }
    }
    return product;
}

bool supported_in_parameters(const Basis& rows, const Basis& prime, size_t n) {
    // I is extended from a coordinate subring S whose variables lie in P.
    // For homogeneous I in S each associated prime is homogeneous, hence
    // contained in its irrelevant ideal; polynomial extension preserves this.
    std::vector<bool> used(n);
    for (const auto& f : rows) {
        std::optional<mpz_class> degree;
        for (const auto& [e,c] : f) {
            mpz_class d = 0;
            for (size_t i = 0; i < n; ++i) if (e[i] != 0) { used[i] = true; d += e[i]; }
            if (degree && d != *degree) return false;
            degree = std::move(d);
        }
    }
    for (size_t i = 0; i < n; ++i) if (used[i]) {
        Powers e(n);
        e[i] = 1;
        if (!member_lex({{e,1}},prime)) return false;
    }
    return true;
}

