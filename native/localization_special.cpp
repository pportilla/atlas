std::optional<Basis> special_contraction(const Basis& generators,const Basis& prime,size_t n) {
    const Basis unit{Polynomial{{Powers(n),1}}};
    Basis rows;
    for (const auto& f : generators) if (!f.empty()) rows.push_back(f);
    if (rows.empty()) return Basis{};
    if (prime.empty()) return unit;
    if (std::all_of(rows.begin(),rows.end(),[](const auto& f){return f.size()==1;}))
        return monomial_contraction(rows,prime,n);

    if (prime.size() == 1) return Basis{height_one(rows,prime.front(),n)};

    for (const auto& f : rows) if (!member_lex(f,prime)) return unit;
    if (rows.size()==1) return Basis{nonunit_part(rows.front(),prime,n)};
    if (supported_in_parameters(rows,prime,n)) return primary::reduced(rows,n,true);

    // Write I = hK and h = u*v, with u a local unit and all irreducible
    // factors of v in P. A witness s outside P is coprime to v. Thus
    // v divides f whenever s*f is in vK, and (I R_P) ∩ R = v*(K R_P ∩ R).
    auto common = local::polynomial_gcd(rows,n);
    if (common && !common->empty() && common->rbegin()->first != Powers(n)) {
        auto v = nonunit_part(*common,prime,n);
        auto residual = contract(local::divide_generators(rows,*common,n),prime,n);
        if (v == unit.front()) return residual;
        for (auto& g : residual) g = primary::multiply(g,v);
        return primary::reduced(residual,n,true);
    }

    if (auto simpler = contract_factored(std::move(rows),prime,n)) return simpler;
    return std::nullopt;
}

std::optional<Basis> contract_factored(Basis rows, const Basis& prime, size_t n) {
    bool changed = false;
    bool linear_factors = true;
    for (auto& f : rows) {
        auto retained = nonunit_part(f,prime,n,&linear_factors);
        // A nonconstant cancelled factor strictly lowers the leading monomial.
        if (retained.rbegin()->first != f.rbegin()->first) changed = true;
        f = std::move(retained);
    }
    // Independent affine linear forms in P extend to coordinates. Products of
    // such forms are homogeneous in their span. Every associated prime over
    // that subring is homogeneous and contained in P after extension to R.
    if (linear_factors) return primary::reduced(rows,n,true);
    if (changed) return contract(rows,prime,n);
    return std::nullopt;
}
