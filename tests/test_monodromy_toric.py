import json
from collections import Counter
from itertools import product
from math import factorial
from pathlib import Path
import unittest

from engine.binomial_backend import resolve_binomial
from engine.monodromy_toric import _volume, toric_contributions
from engine.newton_backend import resolve_newton
from engine.nonreduced import nonreduced_resolution
from engine.polynomial import parse
from engine.toric_backend import resolve_toric


def group(rows):
    weights = Counter()
    for row in rows:
        weights[row["multiplicity"]] += row["euler_characteristic"]
    return {n:v for n,v in weights.items() if v}


class ToricMonodromy(unittest.TestCase):
    def test_diagonal_surface_in_two_different_fans(self):
        names = list("xyz")
        p = parse("x^2+y^3+z^5",names)
        # Inclusion-exclusion of the 2-, 3-, and 5-fold cyclic permutations.
        expected = {2:1,3:1,5:1,6:-1,10:-1,15:-1,30:1}
        for resolver in (resolve_toric,resolve_newton):
            for mode in ("embedded","intrinsic"):
                result = resolver(p,names,mode)
                self.assertEqual(group(toric_contributions(result,p,names)),expected)

    def test_orbits_over_positive_dimensional_blowup_centers(self):
        names = list("xyzt")
        p = parse("x*y^2*z^3-t^6",names)
        for mode in ("embedded","intrinsic"):
            result = resolve_binomial(p,names,mode)
            rows = toric_contributions(result,p,names)
            self.assertEqual(len(rows),8)
            self.assertEqual(group(rows),{6:1})

    def test_nonreduced_binomial_and_local_unit(self):
        names = list("xyz")
        p = parse("(1+x)*(x*y-z^2)^2*(x*y+z^2)^3",names)
        result = nonreduced_resolution(p,names,"embedded",lambda s:resolve_binomial(s,names,"embedded"))
        self.assertEqual(group(toric_contributions(result,p,names)),{10:1})

    def test_identity_and_smooth_nonreduced_support(self):
        names = list("xyz")
        simple = parse("x-y^3",names)
        result = resolve_binomial(simple,names,"intrinsic")
        self.assertEqual(group(toric_contributions(result,simple,names)),{1:1})
        repeated = parse("(1+z)*(x-y^3)^4",names)
        result = nonreduced_resolution(repeated,names,"embedded",lambda s:resolve_binomial(s,names,"embedded"))
        self.assertEqual(group(toric_contributions(result,repeated,names)),{4:1})

    def test_changed_coordinates_and_weighted_homogeneous_milnor_number(self):
        path = Path(__file__).resolve().parents[1]/"examples/four-variable-intrinsic.json"
        result = json.loads(path.read_text())
        names = result["variables"]
        p = parse(result["polynomial"],names)
        rows = group(toric_contributions(result,p,names))
        self.assertEqual(rows,{5:-3,15:16,45:-16})
        # The principal part has degree 45 and weights (9,14,3,9);
        # its isolated singularity has Milnor number 496.
        self.assertEqual(sum(n*chi for n,chi in rows.items()),1-496)

    def test_normalized_orbit_lattice_volume(self):
        for d in (2,3,4):
            vertices = list(product((0,2),repeat=d))
            points = [(1,)*d,*vertices,*vertices]
            self.assertEqual(_volume(points,d),factorial(d)*2**d)
            self.assertEqual(_volume([(*p,0) for p in points],d+1),0)
        # The index of the character sublattice generated by support
        # differences must be retained in the full orbit lattice.
        self.assertEqual(_volume([(-4,),(-2,),(2,)],1),6)

    def test_unsupported_atlas_defers(self):
        self.assertIsNone(toric_contributions({"status":"inconclusive"}, {}, []))
        self.assertIsNone(toric_contributions({"status":"resolved","engine":"verified-ideal-blowup"},
                                              {}, []))


if __name__ == "__main__":
    unittest.main()
