function ringText(ring) {
  const field = ring.field === "QQ" ? "ℚ" : ring.field;
  return field + (ring.variables.length ? "[" + ring.variables.join(", ") + "]" : "") + " · " + ring.order;
}

function updateSources() {
  const ring = inputRing();
  byId("point-label").textContent = ring.variables.length ? "Coordinates (" + ring.variables.join(", ") + ")" : "Point in zero coordinates";
  byId("point-help").textContent = ring.variables.length
    ? "Enter comma-separated integers or fractions. Leave blank for the origin."
    : "The unique point has no coordinates. Enter () to specify it explicitly, or leave blank for the origin.";
  const ideals = ["ideal", "basis", "local-jacobian-algebra"];
  const quotient = operation.value === "quotient-ring";
  const globalIdealsOnly = ["quotient-ring", ...AlgebraSession.powerOperations, "hilbert-series", "multiplicity", "radical", "primary-decomposition", "normalization", "localization"].includes(operation.value);
  const firstIdealKinds = globalIdealsOnly ? ["ideal", "basis"] : [...ideals];
  if (quotient) firstIdealKinds.push("quotient-ring");
  const polyKinds = quotient ? ["polynomial", "quotient-element"] : ["polynomial"];
  if (AlgebraSession.localBasisInputs.has(operation.value)) firstIdealKinds.push("local-standard-basis");
  if (AlgebraSession.coneInputs.has(operation.value)) firstIdealKinds.push("tangent-cone");
  for (const [source, group, kinds] of [
    ["ideal-source", "first-ideal-inputs", firstIdealKinds],
    ["second-ideal-source", "second-ideal-inputs", ideals],
    ["prime-source", "prime-inputs", ["ideal", "basis"]],
    ["numerator-source", "fraction-numerator", ["polynomial"]],
    ["denominator-source", "fraction-denominator", ["polynomial"]],
    ["polynomial-source", "polynomial", polyKinds],
    ["other-polynomial-source", "other-polynomial", polyKinds],
  ]) {
    const select = byId(source);
    const previous = select.value;
    select.replaceChildren(select.options[0]);
    for (const [name, { result, owner, quotientOwner }] of session.objects) {
      if (!kinds.includes(result.type)) continue;
      let kind = result.type;
      if (result.type === "quotient-element") kind = result.representative;
      else if (result.type === "quotient-ring") kind = "quotient ring";
      else if (owner) kind = result.type === "polynomial" ? result.polynomial : "⟨" + (result.generators.join(", ") || "0") + "⟩";
      if (kind === "local-jacobian-algebra") kind = "Jacobian ideal (partial derivatives)";
      if (kind === "local-standard-basis") kind = "local standard basis " + scopeText(result);
      if (kind === "tangent-cone") kind = "tangent cone " + scopeText(result);
      const option = new Option(name + " · " + kind + " · " + ringText(result.ring), name);
      option.disabled = !AlgebraSession.sameRing(result.ring, ring) ||
        (result.type === "quotient-element" && quotientOwner !== byId("ideal-source").value);
      select.add(option);
      // Preserve the selection on a ring edit. Submission then explains the
      // mismatch rather than silently reverting to different literal operands.
      if (name === previous) option.selected = true;
    }
    byId(source + "-field").hidden = select.options.length === 1;
    showOperandGroup(group, !select.value);
  }
  if (session.objects.get(byId("ideal-source").value)?.result.type === "tangent-cone") {
    byId("point-label").textContent = "Vertex in tangent coordinates (" + ring.variables.join(", ") + ")";
    byId("point-help").textContent = "Leave blank for the vertex, where all tangent coordinates are zero.";
  }
  updateGeneratorExample();
}

