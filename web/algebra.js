function addRow(group, addButton, value = "") {
  const row = document.createElement("div");
  row.className = "generator-row";
  const input = document.createElement("input");
  input.type = "text";
  input.required = true;
  input.autocomplete = "off";
  input.spellcheck = false;
  input.setAttribute("autocapitalize", "off");
  input.value = value;
  const remove = document.createElement("button");
  remove.className = "button";
  remove.type = "button";
  remove.textContent = "×";
  row.append(input, remove);
  group.append(row);
  labelRows(group);
  remove.addEventListener("click", () => {
    const next = row.nextElementSibling || row.previousElementSibling;
    row.remove();
    labelRows(group);
    if (next) next.querySelector("input").focus();
    else addButton.focus();
    markChanges();
  });
  return input;
}

function labelRows(group) {
  const name = { "generators": "Generator", "second-generators": "Second ideal generator",
    "prime-generators": "Prime ideal generator" }[group.id];
  Array.from(group.children).forEach((row, index) => {
    const label = name + " " + (index + 1);
    row.querySelector("input").setAttribute("aria-label", label);
    row.querySelector("button").setAttribute("aria-label", "Remove " + label.toLowerCase());
  });
}

