"""Verify the B1-B9 edge of the archived 36-chart inclined resolution with Singular."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess


ARCHIVE = Path(__file__).with_name("reduced-centre-resolution-ryzen-6800h.json.gz")
# In root chart 27 let (u,v,h) be its coordinates. Off the exceptional divisors,
# u=y/x, v=z/x, h=x/(1+u+v)^2. These three cleared equations and denominators
# give maps of the *ambient* charts that extend to the generic exceptional line.
TRANSITIONS = {
    15: ("u-(1+b),v-(b^2*c-b-2),h*b^2-a", "b"),
    23: ("u-(b-1),v-(b*c-b),h*b-a", "b"),
    30: ("a*u-1,a*v-b,h-a^3*c", "a"),
}


def proof(record):
    charts = record["atlas"]
    def rows(i, names):
        chart = charts[i]
        rename = dict(zip(chart["coordinates"], names))
        def lift(f):
            return re.sub(r"[A-Za-z_][A-Za-z0-9_]*",lambda m: rename[m[0]],f)
        exceptional = {c["id"]: list(map(lift,c["ideal"])) for c in chart["components"]
                       if c["id"].startswith("B")}
        assert not chart["ambient_ideal"] and all(len(v)==1 for v in exceptional.values())
        return ([lift(chart["map"][k]) for k in "xyz"],exceptional,
                [list(map(lift,h)) for h in chart["removed"]],list(map(lift,chart["region"])),
                list(map(lift,chart["fibre"])))
    represented = [i for i,c in enumerate(charts) if {"B1","B9"} <= {d["id"] for d in c["components"]}]
    assert represented == [15,23,27,30]
    body = ['LIB "elim.lib";',
            'proc require(int flag,string claim){if(!flag){ERROR("FAILED "+claim);}}',
            'proc equalIdeals(ideal x,ideal y){return(size(reduce(x,std(y)))==0 && size(reduce(y,std(x)))==0);}',
            'proc isLine(ideal x){list primes=minAssGTZ(x);return(size(primes)==1 && equalIdeals(x,primes[1]) && dim(std(x))==1);}',
            'proc outside(ideal p,ideal hole){return(size(reduce(hole,std(p)))>0);}',
            'proc ownedPoint(ideal p,ideal owned,list removed){ideal s=p+owned;'
            'if(dim(std(s))<0){return(0);}int i;for(i=1;i<=size(removed);i++){if(!outside(s,removed[i])){return(0);}}return(1);}',
            'ring R=0,(a,b,c,u,v,h),dp;']
    root_maps,root_divisors,root_holes,root_region,root_fibre = rows(27,("u","v","h"))
    right = ",".join(root_divisors[k][0] for k in ["B1","B9"])
    counters = {"chart_primes":0,"generic_holes":0,"fibre_contains_line":0,"owned_visible":0,
                "equal_ambient_graphs":0,"equal_prime_graphs":0,"common_regular_denominator":0}
    for i in represented:
        left_names = ("a","b","c")
        maps,divisors,holes,region,fibre = rows(i,left_names)
        p = ",".join(divisors[k][0] for k in ["B1","B9"])
        # Check that the local chart section is exactly one geometrically integral line.
        # The ideal is generated by independent linear forms over QQ.
        body.extend([f'ring r{i}=0,(a,b,c),dp;',f'ideal p={p};',f'ideal fibre={",".join(fibre)};',
                     'require(isLine(p) && deg(p[1])==1 && deg(p[2])==1,"linear prime");',
                     'require(size(reduce(fibre,std(p)))==0,"section over origin");','list removed;'])
        counters["chart_primes"]+=1;counters["fibre_contains_line"]+=1
        for j,hole in enumerate(holes,1):
            body.extend([f'removed[{j}]=ideal({",".join(hole)});',
                         f'require(outside(p,removed[{j}]),"generic point outside removed centre");'])
            counters["generic_holes"]+=1
        body.extend([f'ideal owned={",".join(region) or "0"};', 'require(ownedPoint(p,owned,removed),"owned point");',
                     'setring R;'])
        counters["owned_visible"]+=1
        if i==27:
            continue
        transition,den=TRANSITIONS[i]
        graph = ",".join(f"({left})-({right_map})" for left,right_map in zip(maps,root_maps))
        units = "*".join(f"({ideal[0]})" for ideal in [*divisors.values(),*root_divisors.values()])
        # L is the saturated graph of equal projections away from all exceptional divisors.
        # The explicit chart transition has a polynomial inverse wherever den is a unit.
        body += [f'ideal M{i}={graph};',f'ideal E{i}={transition};',f'ideal P{i}={p};',f'ideal Q{i}={right};',
                 f'ideal L{i}=sat(M{i},ideal({units}));',
                 f'ideal A{i}=sat(L{i},ideal({den}));ideal B{i}=sat(E{i},ideal({den}));',
                 f'require(equalIdeals(A{i},B{i}),"ambient diagonal {i}");',
                 f'ideal T{i}=sat(B{i}+P{i},ideal({den}));ideal U{i}=sat(B{i}+Q{i},ideal({den}));',
                 f'require(equalIdeals(T{i},U{i}) && dim(std(T{i}))==1,"both prime pullbacks {i}");',
                 f'require(outside(T{i},ideal({den})),"nonempty regular locus {i}");']
        for key in ("equal_ambient_graphs","equal_prime_graphs","common_regular_denominator"):counters[key]+=1
    body.extend(['print("PASSED historical B1-B9");','quit;'])
    return "\n".join(body)+"\n",counters


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive",type=Path,default=ARCHIVE)
    parser.add_argument("--singular",default=shutil.which("Singular"))
    parser.add_argument("--output",type=Path,required=True)
    parser.add_argument("--program",type=Path)
    args=parser.parse_args()
    with gzip.open(args.archive) as stream:
        record=json.load(stream)["cases"]["inclined"]["agreed_records"]["before_zetas"]
    program,counts=proof(record)
    if args.program:
        args.program.write_text(program)
    proc=subprocess.run([args.singular,"-q","--no-rc","--random=47","--threads=1"],input=program,
                        text=True,capture_output=True,check=True,timeout=60)
    if proc.stderr or [s for s in proc.stdout.splitlines() if not s.startswith("// ** redefining removed")]!=["PASSED historical B1-B9"]:
        raise RuntimeError(proc.stdout+proc.stderr)
    receipt={"archive":args.archive.name,"archive_sha256":hashlib.sha256(args.archive.read_bytes()).hexdigest(),
             "program_sha256":hashlib.sha256(program.encode()).hexdigest(),"singular":subprocess.check_output(
                 [args.singular,"--version"],text=True).splitlines()[0],"charts":[15,23,27,30],"common_chart":27,
             "certificates":counts,"geometric_components":1,"result":"PASSED historical B1-B9"}
    args.output.write_text(json.dumps(receipt,indent=2)+"\n")


if __name__=="__main__":
    main()
